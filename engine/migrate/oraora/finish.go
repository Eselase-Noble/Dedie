var startWithRe = regexp.MustCompile(`START WITH -?[0-9]+`)

// moveSequence makes a sequence on the target continue from a number.
// Releases from 18c on restart a sequence in place. An older target has
// no statement for it, so there the sequence is dropped and created
// again from its definition with the new starting point; what uses it is
// compiled again when the migration ends.
func (r *runner) moveSequence(ctx context.Context, s Sequence, value string) error {
	name := oracle.QName(s.Schema, s.Name)
	_, err := r.dst.ExecContext(ctx, "ALTER SEQUENCE "+name+" RESTART START WITH "+value)
	if err == nil {
		return nil
	}
	first := oracle.Friendly(err)
	// Only a release that does not know the statement gets the other way.
	if !hasCode(err, "ORA-02286", "ORA-02283", "ORA-00933", "ORA-00922") {
		return first
	}
	for _, stmt := range r.plan.Pre {
		if stmt.Object != "sequence" || stmt.Schema != s.Schema || stmt.Name != s.Name || !startWithRe.MatchString(stmt.SQL) {
			continue
		}
		if _, err := r.dst.ExecContext(ctx, "DROP SEQUENCE "+name); err != nil {
			return oracle.Friendly(err)
		}
		_, err := r.dst.ExecContext(ctx, startWithRe.ReplaceAllString(stmt.SQL, "START WITH "+value))
		return oracle.Friendly(err)
	}
	return first
}

// identityClause writes the GENERATED clause of an identity column.
// While rows are still being stored a column that is ALWAYS on the
// source stays BY DEFAULT, or it would refuse the source's values.
func identityClause(id Identity, final bool, start string) string {
	how := "BY DEFAULT"
	switch {
	case id.Always && final:
		how = "ALWAYS"
	case id.OnNull && !id.Always:
		how = "BY DEFAULT ON NULL"
	}
	clause := oracle.Quote(id.Column) + " GENERATED " + how + " AS IDENTITY"
	if start != "" {
		clause += " (START WITH " + start + ")"
	}
	return clause
}

// syncSequences moves every sequence and identity column on the target
// to where the source's counter stands, so the target never hands out a
// number the source already used. Sequences that were on the target
// before the job and are kept are not part of the plan, and stay where
// they are.
func (r *runner) syncSequences(ctx context.Context) (int, error) {
	next, err := orasrc.SequencePositions(ctx, r.src, r.plan.Catalog)
	if err != nil {
		return 0, err
	}
	n := 0
	for _, s := range r.plan.Sequences {
		v, ok := next[s.Owner+"."+s.Name]
		if !ok {
			continue
		}
		if err := r.moveSequence(ctx, s, v); err != nil {
			return n, fmt.Errorf("%s.%s: %w", s.Schema, s.Name, err)
		}
		n++
	}
	for _, id := range r.plan.Identities {
		v, ok := next[id.Table.Owner+"."+id.Seq]
		if !ok {
			continue
		}
		if _, err := r.dst.ExecContext(ctx, "ALTER TABLE "+id.Table.QName()+" MODIFY ("+identityClause(id, false, v)+")"); err != nil {
			return n, fmt.Errorf("%s.%s: %w", id.Table.Target(), id.Column, oracle.Friendly(err))
		}
		n++
	}
	return n, nil
}

// restoreAlways makes the identity columns GENERATED ALWAYS again that
// are so on the source. It runs when no more rows will be stored.
func (r *runner) restoreAlways(ctx context.Context) {
	for _, id := range r.plan.Identities {
		if !id.Always {
			continue
		}
		if _, err := r.dst.ExecContext(ctx, "ALTER TABLE "+id.Table.QName()+" MODIFY ("+identityClause(id, true, "")+")"); err != nil {
			r.rep.Event("warn", fmt.Sprintf("%s.%s is GENERATED ALWAYS on the source and was left GENERATED BY DEFAULT on the target: %s", id.Table.Target(), id.Column, oracle.Friendly(err)))
		}
	}
}

// compileWith maps the object types of ALL_OBJECTS to the statement that
// compiles one and to the kind the plan knows it by.
var compileWith = map[string][2]string{
	"TYPE":         {"ALTER TYPE %s COMPILE", "type"},
	"TYPE BODY":    {"ALTER TYPE %s COMPILE BODY", "type"},
	"FUNCTION":     {"ALTER FUNCTION %s COMPILE", "function"},
	"PROCEDURE":    {"ALTER PROCEDURE %s COMPILE", "procedure"},
	"PACKAGE":      {"ALTER PACKAGE %s COMPILE", "package"},
	"PACKAGE BODY": {"ALTER PACKAGE %s COMPILE BODY", "package"},
	"VIEW":         {"ALTER VIEW %s COMPILE", "view"},
	"SYNONYM":      {"ALTER SYNONYM %s COMPILE", "synonym"},
	"TRIGGER":      {"ALTER TRIGGER %s COMPILE", "trigger"},
}

// compile brings the objects this job created into a valid state and
// reports those that stay invalid. Stored code and views are created in
// one pass without regard to what depends on what, so some are invalid
// until compiled again, which Oracle would otherwise do on first use.
// Objects the job did not create are not touched, whatever their state.
func (r *runner) compile(ctx context.Context) {
	created := map[string]bool{}
	var schemas []string
	seen := map[string]bool{}
	for _, list := range [][]Stmt{r.plan.Code, r.plan.Final} {
		for _, s := range list {
			if s.Object == "" {
				continue
			}
			created[s.Object+" "+s.Schema+"."+s.Name] = true
			if !seen[s.Schema] {
				seen[s.Schema] = true
				schemas = append(schemas, literal(s.Schema))
			}
		}
	}
	if len(created) == 0 {
		return
	}
	invalid := func() [][]string {
		rows, err := queryText(ctx, r.dst, `SELECT owner, object_name, object_type FROM all_objects
			WHERE owner IN (`+strings.Join(schemas, ", ")+`) AND status = 'INVALID' ORDER BY object_type, object_name`)
		if err != nil {
			return nil
		}
		var ours [][]string
		for _, row := range rows {
			if how, ok := compileWith[row[2]]; ok && created[how[1]+" "+row[0]+"."+row[1]] {
				ours = append(ours, row)
			}
		}
		return ours
	}
	// Twice: compiling one object can invalidate nothing, but it can be
	// what another was waiting for.
	for pass := 0; pass < 2; pass++ {
		for _, row := range invalid() {
			r.dst.ExecContext(ctx, fmt.Sprintf(compileWith[row[2]][0], oracle.QName(row[0], row[1])))
		}
	}
	left := invalid()
	if len(left) == 0 {
		r.rep.Event("info", "stored code and views created on the target all compile")
		return
	}
	var lines []string
	for _, row := range left {
		var why string
		_ = r.dst.QueryRowContext(ctx, `SELECT text FROM (SELECT text FROM all_errors WHERE owner = :1 AND name = :2 AND type = :3 ORDER BY sequence) WHERE ROWNUM = 1`,
			row[0], row[1], row[2]).Scan(&why)
		line := strings.ToLower(row[2]) + " " + row[0] + "." + row[1]
		if why = strings.Join(strings.Fields(why), " "); why != "" {
			line += " (" + why + ")"
		}
		lines = append(lines, line)
	}
	sort.Strings(lines)
	r.rep.Event("warn", fmt.Sprintf("%d object(s) were created but do not compile on the target; they usually depend on something that was not migrated: %s", len(lines), strings.Join(lines, "; ")))
}

// gatherStatistics gives the optimizer statistics for the new tables,
// which rows inserted the ordinary way do not bring with them.
func (r *runner) gatherStatistics(ctx context.Context) {
	for _, t := range r.plan.Tables {
		if _, err := r.dst.ExecContext(ctx, `BEGIN DBMS_STATS.GATHER_TABLE_STATS(:1, :2); END;`, oracle.Quote(t.Schema), oracle.Quote(t.Name)); err != nil {
			r.rep.Event("warn", "gathering optimizer statistics on the target failed; the nightly statistics job will do it instead: "+oracle.Friendly(err).Error())
			return
		}
	}
}
