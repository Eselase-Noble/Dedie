func TestRelease(t *testing.T) {
	// The second number tells 12.1 from 12.2, and from 18c on only counts updates.
	for _, tc := range []struct {
		older, newer string
		same         bool
	}{
		{"12.1.0.2.0", "12.2.0.1.0", false},
		{"12.2.0.1.0", "19.3.0.0.0", false},
		{"19.3.0.0.0", "19.21.0.0.0", true},
		{"19.21.0.0.0", "23.26.1.0.0", false},
		{"23.4.0.24.05", "23.26.1.0.0", true},
	} {
		a, b := release(tc.older), release(tc.newer)
		if (a == b) != tc.same || a > b {
			t.Errorf("release(%s) = %d, release(%s) = %d", tc.older, a, tc.newer, b)
		}
	}
}

func TestParseDefinitions(t *testing.T) {
	text := stmtMark + "CREATE" + fieldMark + "TRG" + fieldMark + "T" + fieldMark + "CREATE TRIGGER x\n" +
		stmtMark + "ALTER" + fieldMark + "TRG" + fieldMark + fieldMark + "ALTER TRIGGER x ENABLE"
	defs := parseDefinitions(text)
	if len(defs) != 2 || defs[0] != (definition{"CREATE", "TRG", "T", "CREATE TRIGGER x\n"}) || defs[1] != (definition{"ALTER", "TRG", "", "ALTER TRIGGER x ENABLE"}) {
		t.Errorf("parsed %#v", defs)
	}
	if defs := parseDefinitions(""); len(defs) != 0 {
		t.Errorf("an empty answer gave %#v", defs)
	}
}

func TestMapSchemas(t *testing.T) {
	privileged := map[string]bool{"CREATE ANY TABLE": true}
	cases := []struct {
		name     string
		owners   []string
		target   target
		want     map[string]string
		problems int
	}{
		{"own schema of the same name", []string{"APP"}, target{User: "APP", Schemas: map[string]bool{"APP": true}}, map[string]string{"APP": "APP"}, 0},
		{"one schema, none of that name", []string{"APP"}, target{User: "NEW"}, map[string]string{"APP": "NEW"}, 0},
		{"one schema, no right to build in it", []string{"APP"}, target{User: "NEW", Schemas: map[string]bool{"APP": true}}, map[string]string{"APP": "NEW"}, 0},
		{"one schema, may build in it", []string{"APP"}, target{User: "DBA1", Schemas: map[string]bool{"APP": true}, Privs: privileged}, map[string]string{"APP": "APP"}, 0},
		{"one schema, privileged but none of that name", []string{"APP"}, target{User: "DBA1", Privs: privileged}, map[string]string{"APP": "DBA1"}, 0},
		{"several schemas", []string{"APP", "HR"}, target{User: "DBA1", Schemas: map[string]bool{"APP": true, "HR": true}, Privs: privileged}, map[string]string{"APP": "APP", "HR": "HR"}, 0},
		{"several, one missing", []string{"APP", "HR"}, target{User: "DBA1", Schemas: map[string]bool{"APP": true}, Privs: privileged}, map[string]string{"APP": "APP"}, 1},
		{"several, no rights", []string{"APP", "HR"}, target{User: "APP", Schemas: map[string]bool{"APP": true, "HR": true}}, map[string]string{"APP": "APP"}, 1},
	}
	for _, tc := range cases {
		got, notes, problems := mapSchemas(tc.owners, &tc.target)
		if len(problems) != tc.problems || len(got) != len(tc.want) || len(notes) != len(tc.want) {
			t.Errorf("%s: mapping %v, %d note(s), problems %v", tc.name, got, len(notes), problems)
		}
		for owner, schema := range tc.want {
			if got[owner] != schema {
				t.Errorf("%s: %s goes to %q, want %q", tc.name, owner, got[owner], schema)
			}
		}
	}
}

func TestWithout(t *testing.T) {
	cfg := migrate.Config{Tables: []string{"orders", "app.items", "HR.PEOPLE"}, ExcludeTables: []string{"app.logs"}}
	got, err := without(cfg, []string{"APP.ORDERS", "HR.PEOPLE"}, "app")
	if err != nil || strings.Join(got.Tables, ",") != "app.items" || strings.Join(got.ExcludeTables, ",") != "app.logs,APP.ORDERS,HR.PEOPLE" {
		t.Errorf("without: %v %v, %v", got.Tables, got.ExcludeTables, err)
	}
	if len(cfg.ExcludeTables) != 1 {
		t.Errorf("the operator's own options were changed: %v", cfg.ExcludeTables)
	}
	// A list that empties must not turn into "every table of the schema".
	if _, err := without(migrate.Config{Tables: []string{"orders"}}, []string{"APP.ORDERS"}, "APP"); err == nil {
		t.Error("keeping every selected table should leave nothing to migrate")
	}
	if got, err := without(migrate.Config{Schemas: []string{"APP"}}, []string{"APP.ORDERS"}, "APP"); err != nil || len(got.Tables) != 0 || len(got.ExcludeTables) != 1 {
		t.Errorf("schema scope: %v %v, %v", got.Tables, got.ExcludeTables, err)
	}
}

