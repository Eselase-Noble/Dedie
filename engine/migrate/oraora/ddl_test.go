func TestRequalify(t *testing.T) {
	cases := []struct{ in, want string }{
		{`CREATE TABLE "OLD"."T" ("A" NUMBER DEFAULT "OLD"."S"."NEXTVAL")`, `CREATE TABLE "NEW"."T" ("A" NUMBER DEFAULT "NEW"."S"."NEXTVAL")`},
		// A literal is data, and a name that only looks like the schema is another name.
		{`COMMENT ON TABLE "OLD"."T" IS 'see "OLD"."T", it''s "OLD".'`, `COMMENT ON TABLE "NEW"."T" IS 'see "OLD"."T", it''s "OLD".'`},
		{`SELECT "OLDER"."T"."A", "OLD" FROM "OLD"."T"`, `SELECT "OLDER"."T"."A", "OLD" FROM "NEW"."T"`},
	}
	for _, tc := range cases {
		if got := requalify(tc.in, "OLD", "NEW"); got != tc.want {
			t.Errorf("requalify(%s)\n got %s\nwant %s", tc.in, got, tc.want)
		}
	}
	if got := requalify(`"OLD"."T"`, "OLD", "OLD"); got != `"OLD"."T"` {
		t.Errorf("the same schema changed the text: %s", got)
	}
}

func TestMentions(t *testing.T) {
	for text, want := range map[string]bool{
		`SELECT COUNT(*) FROM app.orders`:        true,
		`SELECT COUNT(*) FROM App . orders`:      true,
		`SELECT COUNT(*) FROM "APP"."ORDERS"`:    true,
		`SELECT COUNT(*) FROM orders`:            false,
		`SELECT COUNT(*) FROM myapp.orders`:      false,
		`SELECT app_id FROM orders WHERE x = 1.`: false,
		`EXECUTE IMMEDIATE 'DELETE FROM app.t'`:  true,
	} {
		if got := mentions(text, "APP"); got != want {
			t.Errorf("mentions(%q) = %v, want %v", text, got, want)
		}
	}
}

func TestCreateOnly(t *testing.T) {
	for in, want := range map[string]string{
		`CREATE OR REPLACE EDITIONABLE FUNCTION "S"."F" RETURN NUMBER IS BEGIN RETURN 1; END;`: `CREATE EDITIONABLE FUNCTION "S"."F" RETURN NUMBER IS BEGIN RETURN 1; END;`,
		"  CREATE OR REPLACE FORCE EDITIONABLE VIEW \"S\".\"V\" AS SELECT 1 x FROM dual":       `CREATE FORCE EDITIONABLE VIEW "S"."V" AS SELECT 1 x FROM dual`,
		`CREATE UNIQUE INDEX "S"."I" ON "S"."T" ("A")`:                                         `CREATE UNIQUE INDEX "S"."I" ON "S"."T" ("A")`,
		// Only the statement's own opening words, not text further in.
		`CREATE PROCEDURE "S"."P" IS BEGIN EXECUTE IMMEDIATE 'CREATE OR REPLACE VIEW v AS SELECT 1 x FROM dual'; END;`: `CREATE PROCEDURE "S"."P" IS BEGIN EXECUTE IMMEDIATE 'CREATE OR REPLACE VIEW v AS SELECT 1 x FROM dual'; END;`,
	} {
		if got := createOnly(in); got != want {
			t.Errorf("createOnly(%s)\n got %s\nwant %s", in, got, want)
		}
	}
}

