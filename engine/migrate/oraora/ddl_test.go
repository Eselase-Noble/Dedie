func TestCheckExisting(t *testing.T) {
	clashes := []clash{
		{Kind: "table", Schema: "APP", Name: "ORDERS", Held: "table"},
		{Kind: "view", Schema: "APP", Name: "TOTALS", Held: "table"},
		{Kind: "function", Schema: "APP", Name: "TWICE", Held: "function"},
		{Kind: "index", Schema: "APP", Name: "ORDERS_IX", Held: "index"},
	}
	for policy, status := range map[string]string{migrate.ExistingFail: "fail", migrate.ExistingSkip: "warn", migrate.ExistingReplace: "warn"} {
		r := &migrate.Report{}
		checkExisting(r, clashes, policy)
		r.Finish()
		if len(r.Existing) != 4 || r.Existing[1] != (migrate.ExistingObject{Kind: "view", Name: "APP.TOTALS"}) {
			t.Errorf("%s: existing %v", policy, r.Existing)
		}
		if len(r.Checks) != 2 || r.Checks[0].Name != "Target is empty" || r.Checks[1].Name != "Existing objects" ||
			r.Checks[0].Status != status || r.Checks[1].Status != status || r.OK != (status != "fail") {
			t.Errorf("%s: %+v", policy, r.Checks)
		}
		if d := r.Checks[1].Detail; !strings.Contains(d, "views: APP.TOTALS (the name of a table); functions: APP.TWICE; indexes: APP.ORDERS_IX") {
			t.Errorf("%s: %s", policy, d)
		}
		if policy == migrate.ExistingReplace && !strings.Contains(r.Checks[0].Detail, "DROPPED") {
			t.Errorf("replace does not say what it drops: %s", r.Checks[0].Detail)
		}
	}
	r := &migrate.Report{}
	checkExisting(r, nil, migrate.ExistingFail)
	if r.Checks[0].Status != "ok" || r.Checks[1].Status != "ok" || r.Existing != nil {
		t.Errorf("a clean target: %+v", r.Checks)
	}
	if got := dropStatement("table", "APP", "ORDERS"); got != `DROP TABLE "APP"."ORDERS" CASCADE CONSTRAINTS PURGE` {
		t.Error(got)
	}
	if got := dropStatement("materialized view", "APP", "MV"); got != `DROP MATERIALIZED VIEW "APP"."MV"` {
		t.Error(got)
	}
}

func TestRowStatements(t *testing.T) {
	n := func(v int64) sql.NullInt64 { return sql.NullInt64{Int64: v, Valid: true} }
	src := &orasrc.Table{Owner: "OLD", Name: "T", PK: []int{0}, Cols: []orasrc.Column{
		{Name: "ID", DataType: "NUMBER", Precision: n(9), Kind: orasrc.KindNumber},
		{Name: "AT", DataType: "TIMESTAMP(9) WITH TIME ZONE", Kind: orasrc.KindTimestampTZ},
		{Name: "UP", DataType: "VARCHAR2", Virtual: true, Kind: orasrc.KindText},
		{Name: "BIO", DataType: "CLOB", Kind: orasrc.KindText},
	}}
	tbl := &Table{Table: src, Schema: "NEW", stored: []int{0, 1, 3}}
	shape := shapeOf(tbl)
	if shape.params() != 4 {
		t.Fatalf("%d parameters, want three columns and one marker", shape.params())
	}
	if got := readExpr(orasrc.Column{Name: "R", DataType: "BINARY_DOUBLE", Kind: orasrc.KindNumber}); !strings.Contains(got, `"R" IS INFINITE THEN TO_CHAR("R") ELSE TO_CHAR("R", 'TM9'`) {
		t.Errorf("a binary double is read as %s", got)
	}
	if !unprintable(strings.Repeat("#", 64)) || unprintable("1.5") || unprintable(nil) {
		t.Error("unprintable")
	}
	wantSelect := `TO_CHAR("ID", 'TM9', 'NLS_NUMERIC_CHARACTERS=''.,'''), TO_CHAR("AT", 'YYYY-MM-DD HH24:MI:SS.FF9 TZH:TZM'), "BIO", ` +
		`CASE WHEN "BIO" IS NOT NULL AND DBMS_LOB.GETLENGTH("BIO") = 0 THEN '1' END`
	if got := shape.selectList(); got != wantSelect {
		t.Errorf("select list\n got %s\nwant %s", got, wantSelect)
	}
	view := `(SELECT :1 c0, :2 c1, :3 c3, :4 f3 FROM dual) s`
	bio := `CASE WHEN s.f3 = '1' THEN EMPTY_CLOB() ELSE s.c3 END`
	at := `TO_TIMESTAMP_TZ(s.c1, 'YYYY-MM-DD HH24:MI:SS.FF9 TZH:TZM')`
	wantInsert := `INSERT INTO "NEW"."T" ("ID", "AT", "BIO") SELECT TO_NUMBER(s.c0), ` + at + `, ` + bio + ` FROM ` + view
	if got := shape.insertSQL(); got != wantInsert {
		t.Errorf("insert\n got %s\nwant %s", got, wantInsert)
	}
	wantMerge := `MERGE INTO "NEW"."T" t USING ` + view + ` ON (t."ID" = TO_NUMBER(s.c0)) WHEN MATCHED THEN UPDATE SET t."AT" = ` + at + `, t."BIO" = ` + bio +
		` WHEN NOT MATCHED THEN INSERT ("ID", "AT", "BIO") VALUES (TO_NUMBER(s.c0), ` + at + `, ` + bio + `)`
	if got := shape.mergeSQL(); got != wantMerge {
		t.Errorf("merge\n got %s\nwant %s", got, wantMerge)
	}

	b := newBatch(shape)
	b.add([]any{"1", nil, "text"}, []bool{false})
	if args := b.args(); len(args) != 4 || args[0] != (sql.NullString{String: "1", Valid: true}) || args[1] != (sql.NullString{}) {
		t.Errorf("one row is bound as plain values: %#v", args)
	}
	b.add([]any{"2", "2024-02-29 13:14:15.000000000 +05:30", nil}, []bool{true})
	args := b.args()
	ids, ok := args[0].([]sql.NullString)
	flags, ok2 := args[3].([]sql.NullString)
	if !ok || !ok2 || len(ids) != 2 || flags[0].Valid || !flags[1].Valid || b.rows != 2 || b.bytes == 0 {
		t.Errorf("two rows are bound as slices: %#v", args)
	}
}
