package oraora

import (
	"regexp"
	"strings"

	"dedie/engine/connector/oracle"
)

// outsideLiterals applies fn to the parts of a statement that are not
// inside a string literal, and leaves the literals as they are.
func outsideLiterals(text string, fn func(string) string) string {
	var b strings.Builder
	for len(text) > 0 {
		start := strings.IndexByte(text, '\'')
		if start < 0 {
			b.WriteString(fn(text))
			break
		}
		b.WriteString(fn(text[:start]))
		// A quote written twice is a quote inside the literal.
		end := start + 1
		for end < len(text) {
			if text[end] == '\'' {
				if end+1 < len(text) && text[end+1] == '\'' {
					end += 2
					continue
				}
				break
			}
			end++
		}
		end = min(end+1, len(text))
		b.WriteString(text[start:end])
		text = text[end:]
	}
	return b.String()
}

// requalify points a definition at the schema that receives it. Oracle
// stores some expressions with every name written out in full, a column
// default that calls a sequence for one, and DBMS_METADATA hands those
// back as stored: its REMAP_SCHEMA transform changes only the names it
// generates itself. Wherever the source schema is written the way Oracle
// writes it, quoted and followed by a dot, it is replaced here.
func requalify(text, from, to string) string {
	if from == to {
		return text
	}
	old, repl := oracle.Quote(from)+".", oracle.Quote(to)+"."
	return outsideLiterals(text, func(code string) string { return strings.ReplaceAll(code, old, repl) })
}

// mentions reports whether a definition still names a schema: quoted, or
// as a person writes it, in any case and followed by a dot. Such a
// reference inside stored code or a view was written by its author, and
// rewriting it would be guessing; preflight reports it instead.
func mentions(text, schema string) bool {
	if strings.Contains(text, oracle.Quote(schema)) {
		return true
	}
	re, err := regexp.Compile(`(?i)(^|[^A-Za-z0-9_$#"])` + regexp.QuoteMeta(schema) + `\s*\.`)
	return err == nil && re.MatchString(text)
}

var orReplaceRe = regexp.MustCompile(`(?i)^\s*CREATE\s+OR\s+REPLACE\s+`)

// createOnly turns CREATE OR REPLACE, which is how DBMS_METADATA writes
// views, synonyms and stored code, into a plain CREATE. The job only
// creates objects where it has made sure there are none, and if one
// turned up all the same, failing is right and replacing it is not.
func createOnly(text string) string {
	return orReplaceRe.ReplaceAllString(text, "CREATE ")
}

// acceptValues makes identity columns that are GENERATED ALWAYS accept
// the values the source gave its rows. They are made ALWAYS again when
// the migration ends.
func acceptValues(text string) string {
	return outsideLiterals(text, func(code string) string {
		return strings.ReplaceAll(code, "GENERATED ALWAYS AS IDENTITY", "GENERATED BY DEFAULT AS IDENTITY")
	})
}

var commentRe = regexp.MustCompile(`^\s*COMMENT ON [A-Z ]+?\s+"[^"]+"\."([^"]+)"`)

// commentedObject returns the table or view a COMMENT statement is about,
// or an empty string when it cannot be told.
func commentedObject(text string) string {
	if m := commentRe.FindStringSubmatch(text); m != nil {
		return m[1]
	}
	return ""
}

// release reduces a version to the part that decides which DDL a server
// accepts. Up to 12c that is the first two numbers (12.1 and 12.2 are
// different releases); from 18c on the first number is the release and
// the second only counts its updates.
func release(version string) int {
	n := oracle.VersionNum(version)
	if n/10000 >= 18 {
		return n / 10000 * 100
	}
	return n / 100
}

// hasCode reports whether an error carries one of the given ORA- codes.
func hasCode(err error, codes ...string) bool {
	if err == nil {
		return false
	}
	msg := err.Error()
	for _, code := range codes {
		if strings.Contains(msg, code) {
			return true
		}
	}
	return false
}

// alreadyThere recognises the errors that mean a statement's work was
// done before: the name is taken, the table has its primary key, the
// columns have that constraint or index, the column is NOT NULL already.
// A job retried after an interruption passes over what it created the
// first time.
func alreadyThere(err error) bool {
	return hasCode(err, "ORA-00955", "ORA-02260", "ORA-02261", "ORA-02264", "ORA-02275", "ORA-01442", "ORA-01408", "ORA-04081")
}

// notThere recognises the errors of dropping what does not exist.
func notThere(err error) bool {
	return hasCode(err, "ORA-00942", "ORA-04043", "ORA-02289", "ORA-01418", "ORA-04080", "ORA-01434", "ORA-12003")
}
