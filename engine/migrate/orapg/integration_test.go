// setup prepares the source schema and a scratch database on the target.
func setup(t *testing.T, ctx context.Context) (srcCfg, dstCfg connector.Config, src *sql.DB) {
	srcCfg, dstAdmin := testConfig(t, "DEDIE_TEST_ORACLE_SOURCE"), testConfig(t, "DEDIE_TEST_TARGET")
	src, err := oracle.Open(ctx, srcCfg)
	if err != nil {
		t.Fatal(err)
	}
	db := fmt.Sprintf("dedie_o_%d", time.Now().UnixNano())
	pgAdmin, err := postgres.Connect(ctx, dstAdmin)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := pgAdmin.Exec(ctx, "CREATE DATABASE "+db+" ENCODING 'UTF8' TEMPLATE template0"); err != nil {
		t.Fatal(err)
	}
	pgAdmin.Close(ctx)
	t.Cleanup(func() {
		bg := context.Background()
		for _, stmt := range drops {
			src.ExecContext(bg, stmt)
		}
		src.Close()
		if c, err := postgres.Connect(bg, dstAdmin); err == nil {
			c.Exec(bg, "DROP DATABASE IF EXISTS "+db+" WITH (FORCE)")
			c.Close(bg)
		}
	})
	for _, stmt := range drops {
		src.ExecContext(ctx, stmt)
	}
	list := fixture
	_, version, _ := oracle.Version(ctx, src)
	if oracle.VersionNum(version) >= 230000 {
		list = append(list[:len(list):len(list)],
			`CREATE TABLE dedie_it_modern (id NUMBER(9) PRIMARY KEY, doc JSON, ok BOOLEAN)`,
			`INSERT INTO dedie_it_modern VALUES (1, JSON('{"a": [1, 2], "b": "x"}'), TRUE)`,
			`INSERT INTO dedie_it_modern VALUES (2, NULL, FALSE)`)
	}
	for _, stmt := range list {
		if _, err := src.ExecContext(ctx, stmt); err != nil {
			t.Fatalf("fixture: %v\n%s", err, stmt)
		}
	}
	dstCfg = dstAdmin
	dstCfg.Database = db
	return srcCfg, dstCfg, src
}

func mustExec(t *testing.T, ctx context.Context, db interface {
	ExecContext(context.Context, string, ...any) (sql.Result, error)
}, stmts ...string) {
	t.Helper()
	for _, stmt := range stmts {
		if _, err := db.ExecContext(ctx, stmt); err != nil {
			t.Fatalf("%v\n%s", err, stmt)
		}
	}
}

// compare checks every table's row count, and a digest of the columns
// that print alike in both databases.
func compare(t *testing.T, ctx context.Context, src *sql.DB, dst *pgx.Conn) {
	t.Helper()
	for _, tbl := range []string{"dedie_it_customers", "dedie_it_invoices", "dedie_it_events", `"Dedie_It_Mixed"`} {
		var a, b int64
		if err := src.QueryRowContext(ctx, "SELECT COUNT(*) FROM "+tbl).Scan(&a); err != nil {
			t.Fatal(err)
		}
		if err := dst.QueryRow(ctx, "SELECT count(*) FROM dedie_test."+tbl).Scan(&b); err != nil {
			t.Fatal(err)
		}
		if a != b {
			t.Errorf("%s: %d rows on the source, %d on the target", tbl, a, b)
		}
	}
	var a, b string
	if err := src.QueryRowContext(ctx, `SELECT TO_CHAR(SUM(id * 3 + NVL(small, 7) + medium + balance * 100 + LENGTH(code) + NVL(DBMS_LOB.GETLENGTH(bio), 0)
			+ EXTRACT(DAY FROM born) + NVL(ASCII(SUBSTR(code, -1)), 0)), 'TM9') FROM dedie_it_customers`).Scan(&a); err != nil {
		t.Fatal(err)
	}
	if err := dst.QueryRow(ctx, `SELECT sum(id * 3 + coalesce(small, 7) + medium + balance * 100 + length(code) + coalesce(length(bio), 0)
			+ extract(day from born) + ascii(right(code, 1)))::numeric::text FROM dedie_test.dedie_it_customers`).Scan(&b); err != nil {
		t.Fatal(err)
	}
	if strings.TrimSuffix(strings.TrimRight(b, "0"), ".") != a && a != b {
		t.Errorf("customers digest: source %s, target %s", a, b)
	}
	if err := src.QueryRowContext(ctx, `SELECT TO_CHAR(SUM(id + customer_id + amount * 100), 'TM9') FROM dedie_it_invoices`).Scan(&a); err != nil {
		t.Fatal(err)
	}
	if err := dst.QueryRow(ctx, `SELECT coalesce(sum(id + customer_id + amount * 100), 0)::numeric::text FROM dedie_test.dedie_it_invoices`).Scan(&b); err != nil {
		t.Fatal(err)
	}
	if strings.TrimSuffix(strings.TrimRight(b, "0"), ".") != a && a != b {
		t.Errorf("invoices digest: source %s, target %s", a, b)
	}
}

// checkValues looks at one row closely: every type must have arrived
// with the value it had.
func checkValues(t *testing.T, ctx context.Context, dst *pgx.Conn) {
	t.Helper()
	var got string
	err := dst.QueryRow(ctx, `SELECT concat_ws('|', code, name, status, small, medium, big, huge, balance, round(ratio::numeric, 6), round(flt, 6),
			born, created, seen AT TIME ZONE 'UTC', local_seen IS NOT NULL, tenure, shift, length(bio), position(E'\t' in bio) > 0,
			position(E'\n' in bio) > 0, position('\' in bio) > 0, encode(avatar, 'hex'), octet_length(token), ticket >= 100, code_upper)
		FROM dedie_test.dedie_it_customers WHERE code = 'c7'`).Scan(&got)
	if err != nil {
		t.Fatal(err)
	}
	want := "c7|user 7 ☃|A|7|7000|7000000000000|123456789012345678901234567883|8.75|1.000000|2.333333|" +
		"1990-05-24 00:00:00|2024-02-29 13:14:15.123457|2024-02-29 07:44:15.5|t|2 years 6 mons|-1 days -02:03:04.5|3034|t|t|t|00ff10|16|t|C7"
	if got != want {
		t.Errorf("row c7:\n got %s\nwant %s", got, want)
	}
	// The values of a binary double that are not numbers.
	var special string
	if err := dst.QueryRow(ctx, `SELECT string_agg(ratio::text, ',' ORDER BY id) FROM dedie_test.dedie_it_customers WHERE code IN ('c11', 'c12', 'c13')`).Scan(&special); err != nil || special != "Infinity,-Infinity,NaN" {
		t.Errorf("infinities and NaN arrived as %q (%v)", special, err)
	}
	var types string
	err = dst.QueryRow(ctx, `SELECT string_agg(column_name || ' ' || CASE WHEN data_type IN ('numeric', 'character varying', 'character')
			THEN format_type(a.atttypid, a.atttypmod) ELSE data_type END, ', ' ORDER BY ordinal_position)
		FROM information_schema.columns c JOIN pg_attribute a ON a.attrelid = 'dedie_test.dedie_it_customers'::regclass AND a.attname = c.column_name
		WHERE table_schema = 'dedie_test' AND table_name = 'dedie_it_customers'`).Scan(&types)
	if err != nil {
		t.Fatal(err)
	}
	wantTypes := "id bigint, code character varying(20), name character varying(100), status character(1), small smallint, medium integer, big bigint, " +
		"huge numeric(30,0), balance numeric(12,2), ratio double precision, flt numeric, born timestamp without time zone, " +
		"created timestamp without time zone, seen timestamp with time zone, local_seen timestamp with time zone, tenure interval, shift interval, " +
		"bio text, avatar bytea, token bytea, ticket numeric, code_upper character varying(20)"
	if types != wantTypes {
		t.Errorf("translated types:\n got %s\nwant %s", types, wantTypes)
	}
	var mixed string
	if err := dst.QueryRow(ctx, `SELECT "Note" FROM dedie_test."Dedie_It_Mixed" WHERE "Id" = 1`).Scan(&mixed); err != nil || mixed != "kept as written" {
		t.Errorf("mixed-case table: %q, %v", mixed, err)
	}
	var modern bool
	_ = dst.QueryRow(ctx, `SELECT to_regclass('dedie_test.dedie_it_modern') IS NOT NULL`).Scan(&modern)
	if modern {
		var doc string
		var ok bool
		if err := dst.QueryRow(ctx, `SELECT doc->'a'->>1, ok FROM dedie_test.dedie_it_modern WHERE id = 1`).Scan(&doc, &ok); err != nil || doc != "2" || !ok {
			t.Errorf("JSON and BOOLEAN: %q %v %v", doc, ok, err)
		}
	}
}

// checkSchema verifies what was built around the data.
func checkSchema(t *testing.T, ctx context.Context, dst *pgx.Conn) {
	t.Helper()
	var n int
	for what, q := range map[string]string{
		"foreign key":      `SELECT count(*) FROM pg_constraint WHERE conname = 'dedie_it_inv_cust' AND contype = 'f' AND confdeltype = 'c'`,
		"unique index":     `SELECT count(*) FROM pg_indexes WHERE schemaname = 'dedie_test' AND indexname = 'dedie_it_cust_code' AND indexdef LIKE '%UNIQUE%'`,
		"plain index":      `SELECT count(*) FROM pg_indexes WHERE schemaname = 'dedie_test' AND indexname = 'dedie_it_cust_nums'`,
		"check constraint": `SELECT count(*) FROM pg_constraint WHERE conname = 'dedie_it_cust_bal' AND contype = 'c'`,
		"sequence":         `SELECT count(*) FROM pg_sequences WHERE schemaname = 'dedie_test' AND sequencename = 'dedie_it_seq' AND increment_by = 5`,
		"nextval default":  `SELECT count(*) FROM information_schema.columns WHERE table_name = 'dedie_it_customers' AND column_name = 'ticket' AND column_default LIKE 'nextval(%dedie_it_seq%'`,
		"identity":         `SELECT count(*) FROM information_schema.columns WHERE table_name = 'dedie_it_customers' AND column_name = 'id' AND is_identity = 'YES'`,
	} {
		if err := dst.QueryRow(ctx, q).Scan(&n); err != nil || n != 1 {
			t.Errorf("%s: found %d (%v)", what, n, err)
		}
	}
	// New rows must get ids and tickets beyond the source's.
	var id int64
	var ticket float64
	if err := dst.QueryRow(ctx, `INSERT INTO dedie_test.dedie_it_customers (code) VALUES ('new on target') RETURNING id, ticket`).Scan(&id, &ticket); err != nil {
		t.Fatal(err)
	}
	if id <= 3000 || ticket < 100 {
		t.Errorf("identity and sequence were not moved past the source: id %v, ticket %v", id, ticket)
	}
	if _, err := dst.Exec(ctx, `DELETE FROM dedie_test.dedie_it_customers WHERE code = 'new on target'`); err != nil {
		t.Fatal(err)
	}
	if err := dst.QueryRow(ctx, `SELECT count(*) FROM pg_tables WHERE schemaname = 'dedie'`).Scan(&n); err != nil || n != 0 {
		t.Errorf("checkpoint left on the target: %d (%v)", n, err)
	}
}

func logGroups(t *testing.T, ctx context.Context, src *sql.DB) int {
	var n int
	if err := src.QueryRowContext(ctx, `SELECT COUNT(*) FROM user_log_groups WHERE table_name LIKE 'DEDIE_IT%' OR table_name = 'Dedie_It_Mixed'`).Scan(&n); err != nil {
		t.Fatal(err)
	}
	return n
}

func TestMigrationOffline(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	srcCfg, dstCfg, src := setup(t, ctx)

	cfg := migrate.Config{Mode: migrate.ModeOffline}
	report, err := Preflight(ctx, srcCfg, dstCfg, cfg)
	if err != nil {
		t.Fatal(err)
	}
	var noted bool
	for _, c := range report.Checks {
		t.Logf("%-28s %-4s %s", c.Name, c.Status, c.Detail)
		noted = noted || (c.Name == "Offline copy" && c.Status == "warn")
		if c.Name == "Supplemental logging" || c.Name == "LogMiner access" || c.Name == "Primary key logging" {
			t.Errorf("offline preflight checks %q, which only matters when following changes", c.Name)
		}
	}
	if !report.OK || !noted {
		t.Fatalf("preflight: ok %v, offline note %v", report.OK, noted)
	}

	// Writes after the copy starts must neither be carried over nor fail
	// the validation, which reads the source as of the snapshot.
	rep := &memReporter{t: t, desired: "run", tables: map[string]map[string]any{}}
	go func() {
		for i := 0; i < 200; i++ {
			if phase, _ := rep.snapshot(); phase == migrate.PhaseIndexing || phase == migrate.PhaseCutover {
				src.ExecContext(ctx, `INSERT INTO dedie_it_events VALUES ('late', 'written during the copy', SYSDATE)`)
				return
			}
			time.Sleep(20 * time.Millisecond)
		}
	}()
	out, err := Run(ctx, "job-offline", cfg, State{}, srcCfg, dstCfg, rep)
	if err != nil || out != migrate.Completed {
		t.Fatalf("run: %v, %v", out, err)
	}
	if phase, _ := rep.snapshot(); phase != migrate.PhaseDone || rep.Desired() != "run" {
		t.Errorf("phase %s, desired %s", phase, rep.Desired())
	}
	if n := logGroups(t, ctx, src); n != 0 {
		t.Errorf("an offline copy switched on supplemental logging for %d table(s)", n)
	}
	for name, f := range rep.tables {
		if v, _ := f["validation"].(string); !strings.Contains(v, "match") || v == "mismatch" {
			t.Errorf("%s: validation %q", name, v)
		}
	}
	mustExec(t, ctx, src, `DELETE FROM dedie_it_events WHERE kind = 'late'`)

	dst, err := postgres.Connect(ctx, dstCfg)
	if err != nil {
		t.Fatal(err)
	}
	defer dst.Close(ctx)
	compare(t, ctx, src, dst)
	checkValues(t, ctx, dst)
	checkSchema(t, ctx, dst)
}

func TestMigration(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 8*time.Minute)
	defer cancel()
	srcCfg, dstCfg, src := setup(t, ctx)

	cfg := migrate.Config{}
	report, err := Preflight(ctx, srcCfg, dstCfg, cfg)
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range report.Checks {
		t.Logf("%-28s %-4s %s", c.Name, c.Status, c.Detail)
	}
	if !report.OK {
		t.Fatal("preflight failed")
	}

	rep := &memReporter{t: t, desired: "run", tables: map[string]map[string]any{}}
	type result struct {
		out migrate.Outcome
		err error
	}
	done := make(chan result, 1)
	start := func(st State) {
		go func() {
			out, err := Run(ctx, "job-online", cfg, st, srcCfg, dstCfg, rep)
			done <- result{out, err}
		}()
	}
	waitPhase := func(want string) {
		t.Helper()
		for i := 0; i < 1200; i++ {
			select {
			case r := <-done:
				t.Fatalf("job ended while waiting for %s: %v, %v", want, r.out, r.err)
			default:
			}
			if phase, _ := rep.snapshot(); phase == want {
				return
			}
			time.Sleep(100 * time.Millisecond)
		}
		t.Fatalf("timed out waiting for phase %s", want)
	}
	dst, err := postgres.Connect(ctx, dstCfg)
	if err != nil {
		t.Fatal(err)
	}
	defer dst.Close(ctx)
	// converged waits until a query on the target returns what is expected.
	converged := func(what, query, want string) {
		t.Helper()
		var got string
		for i := 0; i < 600; i++ {
			if err := dst.QueryRow(ctx, query).Scan(&got); err == nil && got == want {
				return
			}
			time.Sleep(100 * time.Millisecond)
		}
		t.Fatalf("%s: target has %q, want %q", what, got, want)
	}

	// A transaction left open across the snapshot: its changes are in
	// neither the copy nor, unless mining starts early enough, the stream.
	// Key logging for its table is switched on by hand first, because the
	// job could not do so while the transaction holds the table; the job
	// must then leave that setting as it found it.
	mustExec(t, ctx, src, `ALTER TABLE dedie_it_customers ADD SUPPLEMENTAL LOG DATA (PRIMARY KEY) COLUMNS`)
	early, err := src.BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	mustExec(t, ctx, early, `UPDATE dedie_it_customers SET balance = 4242 WHERE code = 'c10'`)

	start(State{})
	waitPhase(migrate.PhaseStreaming)
	if n := logGroups(t, ctx, src); n < 3 {
		t.Errorf("primary key logging is on for %d table(s), want at least 3", n)
	}
	if err := early.Commit(); err != nil {
		t.Fatal(err)
	}
	converged("transaction open across the snapshot", `SELECT balance::text FROM dedie_test.dedie_it_customers WHERE code = 'c10'`, "4242.00")

	// Ordinary changes of every kind, including a large object rewritten
	// in place and a change of primary key.
	mustExec(t, ctx, src,
		`INSERT INTO dedie_it_customers (code, name, balance, bio, avatar, shift) VALUES ('fresh', N'new ☃ row', 12.5, TO_CLOB(RPAD('q', 4000, 'q')) || RPAD('q', 4000, 'q') || RPAD('q', 1000, 'q'), HEXTORAW('CAFE'), INTERVAL '3 00:00:01' DAY TO SECOND)`,
		`UPDATE dedie_it_customers SET bio = TO_CLOB(RPAD('w', 4000, 'w')) || RPAD('w', 4000, 'w') || RPAD('w', 4000, 'w') || bio, born = DATE '2001-02-03', small = 42 WHERE code = 'c7'`,
		`UPDATE dedie_it_customers SET balance = balance + 1 WHERE id BETWEEN 100 AND 1100`,
		`DELETE FROM dedie_it_customers WHERE id BETWEEN 2000 AND 2100`,
		`UPDATE dedie_it_invoices SET id = id + 1000000 WHERE id BETWEEN 1 AND 50`,
		`UPDATE "Dedie_It_Mixed" SET "Note" = 'changed' WHERE "Id" = 1`,
		`INSERT INTO "Dedie_It_Mixed" VALUES (2, 'it''s, "quoted" and = and')`,
		`INSERT INTO dedie_it_events VALUES ('after', 'not followed: no primary key', SYSDATE)`,
	)
	// A rolled-back transaction leaves nothing behind.
	tx, err := src.BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	mustExec(t, ctx, tx, `UPDATE dedie_it_customers SET code = 'rolled back' WHERE code = 'c5'`, `DELETE FROM dedie_it_invoices WHERE id > 2900`)
	tx.Rollback()
	// So does the part of a transaction undone back to a savepoint, while
	// what came before the savepoint stays.
	mustExec(t, ctx, src, `BEGIN
			UPDATE dedie_it_customers SET medium = 77 WHERE code = 'c6';
			SAVEPOINT sp;
			DELETE FROM dedie_it_customers WHERE code = 'c8';
			UPDATE dedie_it_customers SET medium = 78 WHERE code = 'c9';
			INSERT INTO "Dedie_It_Mixed" VALUES (3, 'undone');
			ROLLBACK TO sp;
			COMMIT;
		END;`)
	// Unique values passed between rows, inside one transaction and across two.
	tx, err = src.BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	mustExec(t, ctx, tx,
		`UPDATE dedie_it_customers SET code = 'swap' WHERE code = 'c1'`,
		`UPDATE dedie_it_customers SET code = 'c1' WHERE code = 'c2'`,
		`UPDATE dedie_it_customers SET code = 'c2' WHERE code = 'swap'`)
	if err := tx.Commit(); err != nil {
		t.Fatal(err)
	}
	mustExec(t, ctx, src,
		`UPDATE dedie_it_customers SET code = 'moving' WHERE code = 'c3'`,
		`UPDATE dedie_it_customers SET code = 'c3' WHERE code = 'c4'`)

	converged("insert", `SELECT concat_ws('|', name, balance, length(bio), encode(avatar, 'hex'), shift) FROM dedie_test.dedie_it_customers WHERE code = 'fresh'`,
		"new ☃ row|12.50|9000|cafe|3 days 00:00:01")
	converged("large object update", `SELECT concat_ws('|', length(bio), born, small) FROM dedie_test.dedie_it_customers WHERE id = 7`, "15034|2001-02-03 00:00:00|42")
	converged("primary key update", `SELECT count(*)::text FROM dedie_test.dedie_it_invoices WHERE id > 1000000`, "50")
	converged("unique swap", `SELECT string_agg(code, ',' ORDER BY id) FROM dedie_test.dedie_it_customers WHERE id IN (1, 2, 3, 4)`, "c2,c1,moving,c3")
	converged("mixed-case table", `SELECT string_agg("Note", ';' ORDER BY "Id") FROM dedie_test."Dedie_It_Mixed"`, `changed;it's, "quoted" and = and`)
	converged("rollback to a savepoint", `SELECT string_agg(code || '=' || medium, ',' ORDER BY id) FROM dedie_test.dedie_it_customers WHERE id IN (6, 8, 9)`, "c6=77,c8=8000,c9=9000")
	converged("rollback", `SELECT count(*)::text FROM dedie_test.dedie_it_customers WHERE code = 'rolled back'`, "0")

	// Pause, change the source while nothing is listening, and resume.
	rep.SetDesired("pause")
	if r := <-done; r.err != nil || r.out != migrate.Paused {
		t.Fatalf("pause: %v, %v", r.out, r.err)
	}
	mustExec(t, ctx, src,
		`UPDATE dedie_it_customers SET status = 'P' WHERE id <= 500`,
		`DELETE FROM dedie_it_customers WHERE id BETWEEN 2500 AND 2520`,
		`TRUNCATE TABLE dedie_it_events`,
	)
	_, st := rep.snapshot()
	rep.SetDesired("run")
	start(st)
	converged("changes made while paused", `SELECT count(*)::text FROM dedie_test.dedie_it_customers WHERE status = 'P'`, "500")
	converged("truncate", `SELECT count(*)::text FROM dedie_test.dedie_it_events`, "0")

	rep.SetDesired("cutover")
	if r := <-done; r.err != nil || r.out != migrate.Completed {
		t.Fatalf("cutover: %v, %v", r.out, r.err)
	}
	_, st = rep.snapshot()
	t.Logf("applied %d transaction(s), %d row(s), %d anomalies", st.TxApplied, st.RowsApplied, st.Anomalies)
	for name, f := range rep.tables {
		if v, _ := f["validation"].(string); !strings.Contains(v, "match") || v == "mismatch" {
			t.Errorf("%s: validation %q", name, v)
		}
	}
	if n := logGroups(t, ctx, src); n != 1 {
		t.Errorf("primary key logging is on for %d table(s) afterwards; only the one switched on before the job should remain", n)
	}
	// The cascade ran on the source; the target must not have kept the
	// invoices of deleted customers, nor lost any other.
	compare(t, ctx, src, dst)
	checkSchema(t, ctx, dst)
}

// existingObjects prepares a source and a target on which the names the
// migration wants for its sequence, an index and two tables are taken. An
// index is named within its schema in PostgreSQL, so one on an unrelated
// table is in the way. A type holds a table's name without being a table.
// The schema merely exists already, which is welcome.
func existingObjects(t *testing.T, ctx context.Context) (srcCfg, dstCfg connector.Config, src *sql.DB, dst *pgx.Conn) {
	t.Helper()
	srcCfg, dstCfg, src = setup(t, ctx)
	dst, err := postgres.Connect(ctx, dstCfg)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { dst.Close(context.Background()) })
	run := func(sql string) {
		t.Helper()
		if _, err := dst.PgConn().Exec(ctx, sql).ReadAll(); err != nil {
			t.Fatal(err)
		}
	}
	run(`CREATE SCHEMA dedie_test; CREATE TABLE dedie_test.unrelated (a int)`)

	// A target that holds none of the names passes, and lists nothing.
	report, err := Preflight(ctx, srcCfg, dstCfg, migrate.Config{Mode: migrate.ModeOffline})
	if err != nil {
		t.Fatal(err)
	}
	if c := findCheck(t, report, "Existing objects"); c.Status != "ok" || !report.OK || len(report.Existing) != 0 {
		t.Fatalf("clean target: ok=%v, existing objects %s: %s, listed %v", report.OK, c.Status, c.Detail, report.Existing)
	}

	run(`SET search_path = dedie_test;
		CREATE SEQUENCE dedie_it_seq;
		SELECT setval('dedie_it_seq', 777);
		CREATE INDEX dedie_it_cust_nums ON unrelated (a);
		CREATE TYPE dedie_it_invoices AS ENUM ('other');
		CREATE TABLE dedie_it_events (other int);
		INSERT INTO dedie_it_events VALUES (42);
		RESET search_path`)
	return srcCfg, dstCfg, src, dst
}

func findCheck(t *testing.T, r *migrate.Report, name string) migrate.Check {
	t.Helper()
	for _, c := range r.Checks {
		if c.Name == name {
			return c
		}
	}
	t.Fatalf("preflight has no %q check", name)
	return migrate.Check{}
}

// existingList is the preflight's list of what the target already has.
func existingList(r *migrate.Report) string {
	var out []string
	for _, e := range r.Existing {
		out = append(out, e.Kind+" "+e.Name)
	}
	sort.Strings(out)
	return strings.Join(out, "; ")
}

// wantExisting is what the preflight must list on the target existingObjects
// prepares, each object under the kind and name the target has it by.
const wantExisting = "index dedie_test.dedie_it_cust_nums; sequence dedie_test.dedie_it_seq; table dedie_test.dedie_it_events; type dedie_test.dedie_it_invoices"

// preexisting describes the objects existingObjects put on the target, with
// what tells one definition of each from another.
func preexisting(t *testing.T, ctx context.Context, dst *pgx.Conn) string {
	t.Helper()
	var s string
	if err := dst.QueryRow(ctx, `SELECT concat_ws(' | ',
		(SELECT string_agg(relname || ':' || relkind::text, ',' ORDER BY relname COLLATE "C") FROM pg_class WHERE relnamespace = 'dedie_test'::regnamespace
			AND relname IN ('unrelated', 'dedie_it_seq', 'dedie_it_cust_nums', 'dedie_it_invoices', 'dedie_it_events')),
		(SELECT string_agg(indexname || ' on ' || tablename, ',') FROM pg_indexes WHERE schemaname = 'dedie_test' AND tablename IN ('unrelated', 'dedie_it_events')),
		(SELECT q.last_value::text || q.is_called::text || s.increment_by::text FROM dedie_test.dedie_it_seq q, pg_sequences s WHERE s.sequencename = 'dedie_it_seq'),
		(SELECT string_agg(enumlabel, ',') FROM pg_enum WHERE enumtypid = 'dedie_test.dedie_it_invoices'::regtype),
		(SELECT string_agg(attname, ',' ORDER BY attnum) FROM pg_attribute WHERE attrelid = 'dedie_test.dedie_it_events'::regclass AND attnum > 0),
		(SELECT string_agg(conname, ',') FROM pg_constraint WHERE conrelid = 'dedie_test.dedie_it_events'::regclass),
		(SELECT string_agg(other::text, ',') FROM dedie_test.dedie_it_events))`).Scan(&s); err != nil {
		t.Fatal(err)
	}
	return s
}

// TestMigrationExistingObjects is the default policy: preflight names every
// object that is in the way, and the job refuses to start and leaves them
// as they were.
func TestMigrationExistingObjects(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	srcCfg, dstCfg, _, dst := existingObjects(t, ctx)
	cfg := migrate.Config{Mode: migrate.ModeOffline}
	before := preexisting(t, ctx, dst)

	report, err := Preflight(ctx, srcCfg, dstCfg, cfg)
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range report.Checks {
		if c.Status == "fail" {
			t.Logf("%-28s %-4s %s", c.Name, c.Status, c.Detail)
		}
	}
	if report.OK {
		t.Error("preflight passed over a target that has the migration's names taken")
	}
	if got := existingList(report); got != wantExisting {
		t.Errorf("existing objects listed:\n got %s\nwant %s", got, wantExisting)
	}
	if c := findCheck(t, report, "Target is empty"); c.Status != "fail" || !strings.Contains(c.Detail, "dedie_test.dedie_it_events") {
		t.Errorf("target is empty: %s: %s", c.Status, c.Detail)
	}
	existing := findCheck(t, report, "Existing objects")
	if existing.Status != "fail" {
		t.Errorf("existing objects: %s", existing.Status)
	}
	for _, want := range []string{
		"tables: dedie_test.dedie_it_invoices (the name of a type)", "sequences: dedie_test.dedie_it_seq",
		"indexes: dedie_test.dedie_it_cust_nums", "never replaces or merges",
	} {
		if !strings.Contains(existing.Detail, want) {
			t.Errorf("existing objects does not mention %q", want)
		}
	}
	if strings.Contains(existing.Detail, "unrelated") || strings.Contains(existing.Detail, "dedie_it_customers") {
		t.Errorf("existing objects names something that is not in the way: %s", existing.Detail)
	}

	rep := &memReporter{t: t, desired: "run", tables: map[string]map[string]any{}}
	out, err := Run(ctx, "job-existing", cfg, State{}, srcCfg, dstCfg, rep)
	if err == nil || !strings.Contains(err.Error(), "preflight failed") ||
		!strings.Contains(err.Error(), "Existing objects") || !strings.Contains(err.Error(), "Target is empty") {
		t.Fatalf("run over existing objects: %v %v", out, err)
	}
	if after := preexisting(t, ctx, dst); after != before {
		t.Errorf("the refused job changed the target:\nbefore %s\nafter  %s", before, after)
	}
	var created bool
	dst.QueryRow(ctx, `SELECT to_regclass('dedie_test.dedie_it_customers') IS NOT NULL OR to_regnamespace('dedie') IS NOT NULL`).Scan(&created)
	if created {
		t.Error("the refused job created objects on the target")
	}
}

// TestMigrationExistingSkip keeps what the target has. The tables whose
// names are taken are left out of the migration; the sequence is neither
// created nor moved at the end, and the index is not created; the rest
// arrives.
func TestMigrationExistingSkip(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	srcCfg, dstCfg, _, dst := existingObjects(t, ctx)
	cfg := migrate.Config{Mode: migrate.ModeOffline, OnExisting: migrate.ExistingSkip}
	before := preexisting(t, ctx, dst)

	report, err := Preflight(ctx, srcCfg, dstCfg, cfg)
	if err != nil {
		t.Fatal(err)
	}
	if !report.OK {
		t.Error("preflight failed although the job keeps what is there")
	}
	if got := existingList(report); got != wantExisting {
		t.Errorf("existing objects listed:\n got %s\nwant %s", got, wantExisting)
	}
	for _, name := range []string{"Target is empty", "Existing objects"} {
		c := findCheck(t, report, name)
		t.Logf("%-28s %-4s %s", c.Name, c.Status, c.Detail)
		if c.Status != "warn" || !strings.Contains(c.Detail, "kept exactly as they are") || !strings.Contains(c.Detail, "left out of the migration") {
			t.Errorf("%s: %s: %s", name, c.Status, c.Detail)
		}
	}

	rep := &memReporter{t: t, desired: "run", tables: map[string]map[string]any{}}
	out, err := Run(ctx, "job-skip", cfg, State{}, srcCfg, dstCfg, rep)
	if err != nil || out != migrate.Completed {
		t.Fatalf("run: %v %v", out, err)
	}
	if after := preexisting(t, ctx, dst); after != before {
		t.Errorf("the job changed what it was told to keep:\nbefore %s\nafter  %s", before, after)
	}
	_, st := rep.snapshot()
	sort.Strings(st.SkippedTables)
	sort.Strings(st.KeptObjects)
	if strings.Join(st.SkippedTables, ",") != "DEDIE_TEST.DEDIE_IT_EVENTS,DEDIE_TEST.DEDIE_IT_INVOICES" ||
		strings.Join(st.KeptObjects, ",") != "index dedie_test.dedie_it_cust_nums,sequence dedie_test.dedie_it_seq" || len(st.DropFirst) != 0 {
		t.Errorf("remembered: skipped %v, kept %v, drop %v", st.SkippedTables, st.KeptObjects, st.DropFirst)
	}
	for name, f := range rep.tables {
		if name == "dedie_it_events" || name == "dedie_it_invoices" {
			t.Errorf("the kept table %s was copied or validated", name)
		}
		if v, _ := f["validation"].(string); !strings.Contains(v, "match") || v == "mismatch" {
			t.Errorf("%s: validation %q", name, v)
		}
	}
	// Everything else arrived.
	checkValues(t, ctx, dst)
	var rows, indexes int
	if err := dst.QueryRow(ctx, `SELECT (SELECT count(*) FROM dedie_test.dedie_it_customers),
		(SELECT count(*) FROM pg_indexes WHERE schemaname = 'dedie_test' AND tablename = 'dedie_it_customers')`).Scan(&rows, &indexes); err != nil {
		t.Fatal(err)
	}
	// The primary key and the unique index, not the index whose name is taken.
	if rows != 3000 || indexes != 2 {
		t.Errorf("customers: %d rows, %d indexes", rows, indexes)
	}

	// A resumed job still knows what it left out, now that its own tables
	// exist as well.
	out, err = Run(ctx, "job-skip", cfg, st, srcCfg, dstCfg, rep)
	if err != nil || out != migrate.Completed {
		t.Fatalf("resumed run: %v %v", out, err)
	}
	if after := preexisting(t, ctx, dst); after != before {
		t.Errorf("the resumed job changed what it was told to keep:\nbefore %s\nafter  %s", before, after)
	}
}

