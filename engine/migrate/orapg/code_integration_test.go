// codeDrops removes everything the code fixture creates; errors for
// objects that are not there are ignored.
var codeDrops = []string{
	`DROP PACKAGE dedie_ic_pkg`,
	`DROP PROCEDURE dedie_ic_wipe`,
	`DROP FUNCTION dedie_ic_ratio`,
	`DROP PROCEDURE dedie_ic_deposit`,
	`DROP FUNCTION dedie_ic_fee`,
	`DROP TABLE dedie_ic_ledger PURGE`,
	`DROP TABLE dedie_ic_audit PURGE`,
	`DROP TABLE dedie_ic_accounts PURGE`,
}

// The stored code of the fixture, one piece for each thing that can
// become of it:
//
//	dedie_ic_fee, dedie_ic_deposit, dedie_ic_acc_audit   convert, and behave the same
//	dedie_ic_ledger_stamp   converts; the test has the target refuse it
//	dedie_ic_ratio          a division that is not rounded: needs review
//	dedie_ic_wipe           builds its statement at run time, which has no conversion
//	dedie_ic_pkg            a package, which is only ever listed
//
// The triggers are created before the rows, so the audit table holds what
// the source's triggers wrote; a trigger that fired on the target for the
// copied rows would write it all again.
var codeFixture = []string{
	`CREATE TABLE dedie_ic_accounts (id NUMBER(9) PRIMARY KEY, owner VARCHAR2(40) NOT NULL, balance NUMBER(12,2) NOT NULL, opened DATE NOT NULL)`,
	`CREATE TABLE dedie_ic_audit (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, account_id NUMBER(9) NOT NULL, action VARCHAR2(10) NOT NULL, amount NUMBER(12,2))`,
	`CREATE TABLE dedie_ic_ledger (id NUMBER(9) PRIMARY KEY, note VARCHAR2(40), entries NUMBER(9))`,
	`CREATE FUNCTION dedie_ic_fee(amount NUMBER) RETURN NUMBER DETERMINISTIC IS
BEGIN
  RETURN ROUND(amount * 0.015, 2);
END;`,
	`CREATE PROCEDURE dedie_ic_deposit(acct NUMBER, amount NUMBER) IS
BEGIN
  UPDATE dedie_ic_accounts SET balance = balance + amount WHERE id = acct;
END;`,
	`CREATE TRIGGER dedie_ic_acc_audit AFTER INSERT OR UPDATE ON dedie_ic_accounts FOR EACH ROW
BEGIN
  IF INSERTING THEN
    INSERT INTO dedie_ic_audit (account_id, action, amount) VALUES (:NEW.id, 'open', :NEW.balance);
  ELSIF :NEW.balance <> :OLD.balance THEN
    INSERT INTO dedie_ic_audit (account_id, action, amount) VALUES (:NEW.id, 'change', :NEW.balance - :OLD.balance);
  END IF;
END;`,
	`CREATE TRIGGER dedie_ic_ledger_stamp BEFORE INSERT OR UPDATE ON dedie_ic_ledger FOR EACH ROW
BEGIN
  :NEW.entries := NVL(:NEW.entries, 0) + 1;
END;`,
	`CREATE FUNCTION dedie_ic_ratio(a NUMBER, b NUMBER) RETURN NUMBER IS
BEGIN
  RETURN a / b;
END;`,
	`CREATE PROCEDURE dedie_ic_wipe(tab VARCHAR2) IS
BEGIN
  EXECUTE IMMEDIATE 'DELETE FROM ' || tab;
END;`,
	`CREATE PACKAGE dedie_ic_pkg AS
  FUNCTION one RETURN NUMBER;
END dedie_ic_pkg;`,
	`INSERT INTO dedie_ic_accounts VALUES (1, 'ada', 100.00, DATE '2024-01-05')`,
	`INSERT INTO dedie_ic_accounts VALUES (2, 'bob', 20.50, DATE '2024-02-11')`,
	`INSERT INTO dedie_ic_accounts VALUES (3, 'cy', 0.00, DATE '2024-03-01')`,
	`UPDATE dedie_ic_accounts SET balance = balance + 5 WHERE id = 2`,
	`INSERT INTO dedie_ic_ledger VALUES (1, 'first', NULL)`,
}

// codeSetup prepares the code fixture in the source schema and a scratch
// database on the target. Both are removed when the test ends.
func codeSetup(t *testing.T, ctx context.Context) (srcCfg, dstCfg connector.Config, src *sql.DB, dst *pgx.Conn) {
	t.Helper()
	srcCfg, dstAdmin := testConfig(t, "DEDIE_TEST_ORACLE_SOURCE"), testConfig(t, "DEDIE_TEST_TARGET")
	src, err := oracle.Open(ctx, srcCfg)
	if err != nil {
		t.Fatal(err)
	}
	db := fmt.Sprintf("dedie_oc_%d", time.Now().UnixNano())
	pgAdmin, err := postgres.Connect(ctx, dstAdmin)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := pgAdmin.Exec(ctx, "CREATE DATABASE "+db+" ENCODING 'UTF8' TEMPLATE template0"); err != nil {
		t.Fatal(err)
	}
	pgAdmin.Close(ctx)
	t.Cleanup(func() {
		bg := context.Background()
		for _, stmt := range codeDrops {
			src.ExecContext(bg, stmt)
		}
		src.Close()
		if c, err := postgres.Connect(bg, dstAdmin); err == nil {
			c.Exec(bg, "DROP DATABASE IF EXISTS "+db+" WITH (FORCE)")
			c.Close(bg)
		}
	})
	for _, stmt := range codeDrops {
		src.ExecContext(ctx, stmt)
	}
	for _, stmt := range codeFixture {
		if _, err := src.ExecContext(ctx, stmt); err != nil {
			t.Fatalf("fixture: %v\n%s", err, stmt)
		}
	}
	dstCfg = dstAdmin
	dstCfg.Database = db
	if dst, err = postgres.Connect(ctx, dstCfg); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { dst.Close(context.Background()) })
	return srcCfg, dstCfg, src, dst
}

// ownCode keeps the parts that concern the code fixture. The source
// schema is migrated whole, and may hold more than this test put there.
func ownCode(parts []string) string {
	var out []string
	for _, l := range parts {
		if strings.Contains(strings.ToLower(l), "dedie_ic_") {
			out = append(out, l)
		}
	}
	return strings.Join(out, "; ")
}

// targetCode lists the fixture's functions, procedures and triggers on
// the target.
func targetCode(t *testing.T, ctx context.Context, dst *pgx.Conn) string {
	t.Helper()
	var names string
	if err := dst.QueryRow(ctx, `SELECT coalesce(string_agg(name, ' ' ORDER BY name), '') FROM (
		SELECT p.proname::text AS name FROM pg_proc p WHERE p.proname LIKE 'dedie\_ic\_%'
		UNION ALL SELECT 'trigger:' || g.tgname FROM pg_trigger g WHERE g.tgname LIKE 'dedie\_ic\_%' AND NOT g.tgisinternal) x`).Scan(&names); err != nil {
		t.Fatal(err)
	}
	return names
}

func codeResults(st State) string {
	var out []string
	for _, r := range st.Code {
		s := r.Kind + " " + r.Name[strings.Index(r.Name, ".")+1:] + "=" + r.Status
		if r.Review {
			s += " (review)"
		}
		out = append(out, s)
	}
	return ownCode(out)
}

func codeLeft(list []migrate.Leftover) string {
	var out []string
	for _, l := range list {
		out = append(out, l.Kind+" "+l.Name[strings.Index(l.Name, ".")+1:])
	}
	return ownCode(out)
}

// runCode runs a one-time copy to its end. during, when given, is called
// once the tables are in and validated, just before the stored code is
// created.
func runCode(t *testing.T, ctx context.Context, srcCfg, dstCfg connector.Config, cfg migrate.Config, during func()) (State, []string) {
	t.Helper()
	var warnings []string
	rep := &levelReporter{memReporter: &memReporter{t: t, desired: "run", tables: map[string]map[string]any{}}, on: func(level, msg string) {
		if level == "warn" {
			warnings = append(warnings, msg)
		}
		if during != nil && strings.HasPrefix(msg, "creating the converted functions") {
			during()
		}
	}}
	out, err := Run(ctx, fmt.Sprintf("code-%d", time.Now().UnixNano()), cfg, State{}, srcCfg, dstCfg, rep)
	if err != nil || out != migrate.Completed {
		t.Fatalf("job: %v, %v", out, err)
	}
	_, st := rep.snapshot()
	return st, warnings
}

// TestMigrationCode follows the stored code of a schema through a
// migration with the default setting: what preflight and the preview say,
// what the job creates and whether it then behaves as on the source, and
// what the administrator is handed for the rest.
func TestMigrationCode(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	srcCfg, dstCfg, src, dst := codeSetup(t, ctx)
	cfg := migrate.Config{Mode: migrate.ModeOffline}
	owner := strings.ToUpper(srcCfg.Username)
	schema := pgName(owner)

	report, err := Preflight(ctx, srcCfg, dstCfg, cfg)
	if err != nil {
		t.Fatal(err)
	}
	if !report.OK {
		t.Fatalf("preflight failed: %+v", report.Checks)
	}
	check := findCheck(t, report, "Stored code")
	t.Logf("preflight Stored code: %s\n%s", check.Status, check.Detail)
	for _, part := range []string{
		"are converted and created at the end",
		"function " + owner + ".DEDIE_IC_FEE, procedure " + owner + ".DEDIE_IC_DEPOSIT, trigger " + owner + ".DEDIE_IC_ACC_AUDIT, trigger " + owner + ".DEDIE_IC_LEDGER_STAMP",
		"need review and are not created", "function " + owner + ".DEDIE_IC_RATIO",
		"cannot be converted and are left for you", "procedure " + owner + ".DEDIE_IC_WIPE",
		"What the conversion takes for granted:", "Oracle's SYSDATE is in the time zone of the database server",
	} {
		if !strings.Contains(check.Detail, part) {
			t.Errorf("stored code check lacks %q", part)
		}
	}

	// The preview ends with the code the job will create: routines, then
	// triggers, each trigger after the function PostgreSQL keeps its code in.
	list, err := Preview(ctx, srcCfg, dstCfg, cfg)
	if err != nil {
		t.Fatal(err)
	}
	checkPhaseOrder(t, list)
	var previewed []string
	for _, s := range list {
		if s.Kind == "function" || s.Kind == "procedure" || s.Kind == "trigger" {
			previewed = append(previewed, s.Phase+" "+s.Kind+" "+strings.TrimPrefix(s.Name, schema+"."))
		}
	}
	if got, want := ownCode(previewed), "cutover function dedie_ic_fee; cutover procedure dedie_ic_deposit; "+
		"cutover function dedie_ic_acc_audit_fn; cutover trigger dedie_ic_acc_audit; cutover function dedie_ic_ledger_stamp_fn; cutover trigger dedie_ic_ledger_stamp"; got != want {
		t.Errorf("previewed code:\n got %s\nwant %s", got, want)
	}

	// Before the job runs, what it will create is not left behind; the
	// routine for review comes with its draft and the notes.
	left, err := pipeline{}.Leftovers(ctx, srcCfg, dstCfg, cfg, nil)
	if err != nil {
		t.Fatal(err)
	}
	if got, want := codeLeft(left), "function DEDIE_IC_RATIO; procedure DEDIE_IC_WIPE; package DEDIE_IC_PKG"; got != want {
		t.Errorf("not migrated:\n got %s\nwant %s", got, want)
	}
	ratio := findLeftover(t, left, "function", "DEDIE_IC_RATIO")
	if ratio.Status != "review" || len(ratio.Notes) == 0 || !strings.Contains(ratio.Draft, "CREATE FUNCTION "+schema+".dedie_ic_ratio(") ||
		!strings.Contains(ratio.Source, "RETURN a / b;") || ratio.End != "/" || !strings.Contains(ratio.Reason, "have to be checked by a person") {
		t.Errorf("ratio: %+v", ratio)
	}
	t.Logf("ratio notes: %q", ratio.Notes)
	wipe := findLeftover(t, left, "procedure", "DEDIE_IC_WIPE")
	if wipe.Status != "unconverted" || wipe.Draft != "" || len(wipe.Notes) == 0 || !strings.Contains(wipe.Reason, "has no conversion: line") || !strings.Contains(wipe.Source, "EXECUTE IMMEDIATE") {
		t.Errorf("wipe: %+v", wipe)
	}
	if pkg := findLeftover(t, left, "package", "DEDIE_IC_PKG"); pkg.Status != "unconverted" || !strings.Contains(pkg.Reason, "packages have no counterpart") {
		t.Errorf("package: %+v", pkg)
	}

	// While the job runs the ledger moves away under it, so that the
	// target refuses the trigger after it has taken the trigger's function.
	st, warnings := runCode(t, ctx, srcCfg, dstCfg, cfg, func() {
		if _, err := dst.Exec(ctx, `ALTER TABLE "`+schema+`".dedie_ic_ledger RENAME TO dedie_ic_ledger_moved`); err != nil {
			t.Error(err)
		}
	})
	if got, want := codeResults(st), "function DEDIE_IC_FEE=created; procedure DEDIE_IC_DEPOSIT=created; trigger DEDIE_IC_ACC_AUDIT=created; trigger DEDIE_IC_LEDGER_STAMP=not created"; got != want {
		t.Errorf("what became of the code:\n got %s\nwant %s", got, want)
	}
	if got, want := targetCode(t, ctx, dst), "dedie_ic_acc_audit_fn dedie_ic_deposit dedie_ic_fee trigger:dedie_ic_acc_audit"; got != want {
		t.Errorf("code on the target:\n got %s\nwant %s", got, want)
	}
	refused := false
	for _, w := range warnings {
		refused = refused || strings.Contains(w, ".DEDIE_IC_LEDGER_STAMP was not created on the target: the target did not accept the converted trigger")
	}
	if !refused {
		t.Errorf("no warning about the refused trigger: %q", warnings)
	}
	if st.Objects == nil || st.Objects.Created < 3 || st.Objects.Left < 4 {
		t.Errorf("summary: %+v", st.Objects)
	}

	// The triggers did not fire for the rows that were copied: the audit
	// table holds what the source's holds.
	if _, err := dst.Exec(ctx, `SET search_path = "`+schema+`"`); err != nil {
		t.Fatal(err)
	}
	srcAudit := func() string {
		var s sql.NullString
		if err := src.QueryRowContext(ctx, `SELECT LISTAGG(account_id || ':' || action || ':' || TO_CHAR(amount, 'FM999990.00'), ' ') WITHIN GROUP (ORDER BY id) FROM dedie_ic_audit`).Scan(&s); err != nil {
			t.Fatal(err)
		}
		return s.String
	}
	dstAudit := func() string {
		var s string
		if err := dst.QueryRow(ctx, `SELECT coalesce(string_agg(account_id || ':' || action || ':' || amount, ' ' ORDER BY id), '') FROM dedie_ic_audit`).Scan(&s); err != nil {
			t.Fatal(err)
		}
		return s
	}
	if a, b := srcAudit(), dstAudit(); a != b || a != "1:open:100.00 2:open:20.50 3:open:0.00 2:change:5.00" {
		t.Errorf("audit after the copy:\nsource %s\ntarget %s", a, b)
	}

	// The same calls and the same changes on both sides give the same.
	var srcFee, dstFee string
	if err := src.QueryRowContext(ctx, `SELECT TO_CHAR(dedie_ic_fee(1234.56)) FROM dual`).Scan(&srcFee); err != nil {
		t.Fatal(err)
	}
	if err := dst.QueryRow(ctx, `SELECT dedie_ic_fee(1234.56)::text`).Scan(&dstFee); err != nil {
		t.Fatal(err)
	}
	if srcFee != dstFee || srcFee != "18.52" {
		t.Errorf("fee(1234.56) is %s on the source and %s on the target", srcFee, dstFee)
	}
	if _, err := src.ExecContext(ctx, `BEGIN dedie_ic_deposit(1, 50); END;`); err != nil {
		t.Fatal(err)
	}
	if _, err := dst.Exec(ctx, `CALL dedie_ic_deposit(1, 50)`); err != nil {
		t.Fatal(err)
	}
	for _, stmt := range []string{
		`INSERT INTO dedie_ic_accounts VALUES (4, 'dee', 7.25, DATE '2024-04-01')`,
		`UPDATE dedie_ic_accounts SET owner = 'bobby' WHERE id = 2`,
		`UPDATE dedie_ic_accounts SET balance = balance - 0.50 WHERE id >= 3`,
	} {
		if _, err := src.ExecContext(ctx, stmt); err != nil {
			t.Fatalf("source: %v\n%s", err, stmt)
		}
		if _, err := dst.Exec(ctx, stmt); err != nil {
			t.Fatalf("target: %v\n%s", err, stmt)
		}
	}
	if a, b := srcAudit(), dstAudit(); a != b || !strings.HasSuffix(a, "1:change:50.00 4:open:7.25 3:change:-0.50 4:change:-0.50") {
		t.Errorf("audit after the same changes on both sides:\nsource %s\ntarget %s", a, b)
	}

	// Afterwards the trigger the target refused is handed over too, with
	// the target's message and the draft.
	raw, _ := json.Marshal(st)
	left, err = pipeline{}.Leftovers(ctx, srcCfg, dstCfg, cfg, raw)
	if err != nil {
		t.Fatal(err)
	}
	if got, want := codeLeft(left), "function DEDIE_IC_RATIO; procedure DEDIE_IC_WIPE; package DEDIE_IC_PKG; trigger DEDIE_IC_LEDGER_STAMP"; got != want {
		t.Errorf("not migrated after the job:\n got %s\nwant %s", got, want)
	}
	if l := findLeftover(t, left, "trigger", "DEDIE_IC_LEDGER_STAMP"); l.Status != "not created" || !strings.Contains(l.Reason, "did not accept the converted trigger") || !strings.Contains(l.Draft, "CREATE TRIGGER") {
		t.Errorf("ledger_stamp: %+v", l)
	}
}

// TestMigrationCodeReview: told to, a job also creates the routines that
// need review, and says which they are. What has no conversion is still
// not created. The trigger that changes a row before it is stored does so
// on both sides.
func TestMigrationCodeReview(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	srcCfg, dstCfg, src, dst := codeSetup(t, ctx)
	schema := pgName(strings.ToUpper(srcCfg.Username))
	cfg := migrate.Config{Mode: migrate.ModeOffline, Code: migrate.CodeReview}

	report, err := Preflight(ctx, srcCfg, dstCfg, cfg)
	if err != nil {
		t.Fatal(err)
	}
	if c := findCheck(t, report, "Stored code"); !strings.Contains(c.Detail, "are converted and created as well, as chosen") || !strings.Contains(c.Detail, ".DEDIE_IC_RATIO") {
		t.Errorf("stored code check: %s", c.Detail)
	}
	st, warnings := runCode(t, ctx, srcCfg, dstCfg, cfg, nil)
	if !strings.Contains(codeResults(st), "function DEDIE_IC_RATIO=created (review)") || strings.Contains(codeResults(st), "WIPE") {
		t.Errorf("what became of the code: %s", codeResults(st))
	}
	if got, want := targetCode(t, ctx, dst), "dedie_ic_acc_audit_fn dedie_ic_deposit dedie_ic_fee dedie_ic_ledger_stamp_fn dedie_ic_ratio trigger:dedie_ic_acc_audit trigger:dedie_ic_ledger_stamp"; got != want {
		t.Errorf("code on the target:\n got %s\nwant %s", got, want)
	}
	warned := false
	for _, w := range warnings {
		warned = warned || strings.Contains(w, ".DEDIE_IC_RATIO, which needs review")
	}
	if !warned {
		t.Errorf("no warning that the ratio needs review: %q", warnings)
	}
	if st.Objects == nil || st.Objects.Review < 1 {
		t.Errorf("summary: %+v", st.Objects)
	}
	if _, err := dst.Exec(ctx, `SET search_path = "`+schema+`"`); err != nil {
		t.Fatal(err)
	}
	for _, stmt := range []string{`INSERT INTO dedie_ic_ledger VALUES (2, 'second', NULL)`, `UPDATE dedie_ic_ledger SET note = 'again' WHERE id = 2`} {
		if _, err := src.ExecContext(ctx, stmt); err != nil {
			t.Fatal(err)
		}
		if _, err := dst.Exec(ctx, stmt); err != nil {
			t.Fatal(err)
		}
	}
	var srcEntries, dstEntries int
	if err := src.QueryRowContext(ctx, `SELECT entries FROM dedie_ic_ledger WHERE id = 2`).Scan(&srcEntries); err != nil {
		t.Fatal(err)
	}
	if err := dst.QueryRow(ctx, `SELECT entries FROM dedie_ic_ledger WHERE id = 2`).Scan(&dstEntries); err != nil {
		t.Fatal(err)
	}
	if srcEntries != dstEntries || srcEntries != 2 {
		t.Errorf("ledger entries: %d on the source, %d on the target", srcEntries, dstEntries)
	}

	raw, _ := json.Marshal(st)
	left, err := pipeline{}.Leftovers(ctx, srcCfg, dstCfg, cfg, raw)
	if err != nil {
		t.Fatal(err)
	}
	if got, want := codeLeft(left), "function DEDIE_IC_RATIO; procedure DEDIE_IC_WIPE; package DEDIE_IC_PKG"; got != want {
		t.Errorf("listed after the job: %s, want %s", got, want)
	}
	if l := findLeftover(t, left, "function", "DEDIE_IC_RATIO"); l.Status != "created, needs review" || len(l.Notes) == 0 || l.Draft == "" {
		t.Errorf("ratio: %+v", l)
	}
}

// TestMigrationCodeOffAndScope: with conversion switched off nothing is
// created and all of the code is handed over as the source defines it;
// and a migration of hand-picked tables converts their triggers only.
