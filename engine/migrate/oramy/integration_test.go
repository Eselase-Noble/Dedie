func TestMigrationOffline(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	srcCfg, dstCfg, src, dst := setup(t, ctx)

	cfg := migrate.Config{Mode: migrate.ModeOffline}
	report, err := Preflight(ctx, srcCfg, dstCfg, cfg)
	if err != nil {
		t.Fatal(err)
	}
	var noted bool
	details := map[string]string{}
	for _, c := range report.Checks {
		t.Logf("%-28s %-4s %s", c.Name, c.Status, c.Detail)
		details[c.Name] = c.Detail
		noted = noted || (c.Name == "Offline copy" && c.Status == "warn")
		if c.Name == "Supplemental logging" || c.Name == "LogMiner access" || c.Name == "Primary key logging" {
			t.Errorf("offline preflight checks %q, which only matters when following changes", c.Name)
		}
	}
	if !report.OK || !noted {
		t.Fatalf("preflight: ok %v, offline note %v", report.OK, noted)
	}
	// What MySQL cannot take over as it is must be said beforehand.
	for name, fragments := range map[string][]string{
		"Not migrated": {"DEDIE_IT_SEQ"},
		"Translated with changes": {"NEXTVAL", "without a precision", "DEDIE_IT_WIDE_A", "DEDIE_IT_CUST_FN", "stored as TEXT instead of VARCHAR(4000)",
			"stored as BIGINT instead of DECIMAL(65,30)", "virtual column", "ISO 8601", "in UTC"},
	} {
		for _, f := range fragments {
			if !strings.Contains(details[name], f) {
				t.Errorf("preflight check %q does not mention %q", name, f)
			}
		}
	}

	// Writes after the copy starts must neither be carried over nor fail
	// the validation, which reads the source as of the snapshot.
	rep := &memReporter{t: t, desired: "run", tables: map[string]map[string]any{}}
	go func() {
		for i := 0; i < 200; i++ {
			if phase, _ := rep.snapshot(); phase == migrate.PhaseIndexing || phase == migrate.PhaseCutover {
				src.ExecContext(ctx, `INSERT INTO dedie_it_events VALUES ('late', 'written during the copy', SYSDATE)`)
				return
			}
			time.Sleep(20 * time.Millisecond)
		}
	}()
	out, err := Run(ctx, "job-offline", cfg, State{}, srcCfg, dstCfg, rep)
	if err != nil || out != migrate.Completed {
		t.Fatalf("run: %v, %v", out, err)
	}
	if phase, _ := rep.snapshot(); phase != migrate.PhaseDone || rep.Desired() != "run" {
		t.Errorf("phase %s, desired %s", phase, rep.Desired())
	}
	if n := logGroups(t, ctx, src); n != 0 {
		t.Errorf("an offline copy switched on supplemental logging for %d table(s)", n)
	}
	rep.validated(t)
	mustExec(t, ctx, src, `DELETE FROM dedie_it_events WHERE kind = 'late'`)

	compare(t, ctx, src, dst)
	checkValues(t, ctx, dst)
	checkSchema(t, ctx, dst)
}

func TestMigration(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 8*time.Minute)
	defer cancel()
	srcCfg, dstCfg, src, dst := setup(t, ctx)

	cfg := migrate.Config{}
	report, err := Preflight(ctx, srcCfg, dstCfg, cfg)
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range report.Checks {
		t.Logf("%-28s %-4s %s", c.Name, c.Status, c.Detail)
	}
	if !report.OK {
		t.Fatal("preflight failed")
	}

	rep := &memReporter{t: t, desired: "run", tables: map[string]map[string]any{}}
	type result struct {
		out migrate.Outcome
		err error
	}
	done := make(chan result, 1)
	start := func(st State) {
		go func() {
			out, err := Run(ctx, "job-online", cfg, st, srcCfg, dstCfg, rep)
			done <- result{out, err}
		}()
	}
	waitPhase := func(want string) {
		t.Helper()
		for i := 0; i < 1200; i++ {
			select {
			case r := <-done:
				t.Fatalf("job ended while waiting for %s: %v, %v", want, r.out, r.err)
			default:
			}
			if phase, _ := rep.snapshot(); phase == want {
				return
			}
			time.Sleep(100 * time.Millisecond)
		}
		t.Fatalf("timed out waiting for phase %s", want)
	}
	// converged waits until a query on the target returns what is expected.
	converged := func(what, query, want string) {
		t.Helper()
		var got string
		for i := 0; i < 600; i++ {
			if err := dst.QueryRowContext(ctx, query).Scan(&got); err == nil && got == want {
				return
			}
			time.Sleep(100 * time.Millisecond)
		}
		t.Fatalf("%s: target has %q, want %q", what, got, want)
	}

	// A transaction left open across the snapshot: its changes are in
	// neither the copy nor, unless mining starts early enough, the stream.
	// Key logging for its table is switched on by hand first, because the
	// job could not do so while the transaction holds the table; the job
	// must then leave that setting as it found it.
	mustExec(t, ctx, src, `ALTER TABLE dedie_it_customers ADD SUPPLEMENTAL LOG DATA (PRIMARY KEY) COLUMNS`)
	early, err := src.BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	mustExec(t, ctx, early, `UPDATE dedie_it_customers SET balance = 4242 WHERE code = 'c10'`)

	start(State{})
	waitPhase(migrate.PhaseStreaming)
	if n := logGroups(t, ctx, src); n < 3 {
		t.Errorf("primary key logging is on for %d table(s), want at least 3", n)
	}
	if err := early.Commit(); err != nil {
		t.Fatal(err)
	}
	converged("transaction open across the snapshot", `SELECT CAST(balance AS CHAR) FROM dedie_it_customers WHERE code = 'c10'`, "4242.00")

	// Ordinary changes of every kind, including a large object rewritten
	// in place and a change of primary key.
	mustExec(t, ctx, src,
		`INSERT INTO dedie_it_customers (code, name, balance, bio, avatar, shift) VALUES ('fresh', N'new ☃ row', 12.5, TO_CLOB(RPAD('q', 4000, 'q')) || RPAD('q', 4000, 'q') || RPAD('q', 1000, 'q'), HEXTORAW('CAFE'), INTERVAL '3 00:00:01' DAY TO SECOND)`,
		`UPDATE dedie_it_customers SET bio = TO_CLOB(RPAD('w', 4000, 'w')) || RPAD('w', 4000, 'w') || RPAD('w', 4000, 'w') || bio, born = DATE '2001-02-03', small = 42 WHERE code = 'c7'`,
		`UPDATE dedie_it_customers SET balance = balance + 1 WHERE id BETWEEN 100 AND 1100`,
		`DELETE FROM dedie_it_customers WHERE id BETWEEN 2000 AND 2100`,
		`UPDATE dedie_it_invoices SET id = id + 1000000 WHERE id BETWEEN 1 AND 50`,
		`UPDATE "Dedie_It_Mixed" SET "Note" = 'changed' WHERE "Id" = 1`,
		`INSERT INTO "Dedie_It_Mixed" VALUES (2, 'it''s, "quoted" and = and')`,
		`INSERT INTO dedie_it_events VALUES ('after', 'not followed: no primary key', SYSDATE)`,
		// Rows found by a key that is no whole number.
		`UPDATE dedie_it_wide SET a = 'changed', b = 'short now' WHERE id = 1.5`,
		`DELETE FROM dedie_it_wide WHERE id = 0.25`,
		`UPDATE dedie_it_wide SET id = 7.125 WHERE id = -3`,
	)
	// A rolled-back transaction leaves nothing behind.
	tx, err := src.BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	mustExec(t, ctx, tx, `UPDATE dedie_it_customers SET code = 'rolled back' WHERE code = 'c5'`, `DELETE FROM dedie_it_invoices WHERE id > 2900`)
	tx.Rollback()
	// So does the part of a transaction undone back to a savepoint, while
	// what came before the savepoint stays.
	mustExec(t, ctx, src, `BEGIN
			UPDATE dedie_it_customers SET medium = 77 WHERE code = 'c6';
			SAVEPOINT sp;
			DELETE FROM dedie_it_customers WHERE code = 'c8';
			UPDATE dedie_it_customers SET medium = 78 WHERE code = 'c9';
			INSERT INTO "Dedie_It_Mixed" VALUES (3, 'undone');
			ROLLBACK TO sp;
			COMMIT;
		END;`)
	// Unique values passed between rows, inside one transaction and across two.
	tx, err = src.BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	mustExec(t, ctx, tx,
		`UPDATE dedie_it_customers SET code = 'swap' WHERE code = 'c1'`,
		`UPDATE dedie_it_customers SET code = 'c1' WHERE code = 'c2'`,
		`UPDATE dedie_it_customers SET code = 'c2' WHERE code = 'swap'`)
	if err := tx.Commit(); err != nil {
		t.Fatal(err)
	}
	mustExec(t, ctx, src,
		`UPDATE dedie_it_customers SET code = 'moving' WHERE code = 'c3'`,
		`UPDATE dedie_it_customers SET code = 'c3' WHERE code = 'c4'`)

	converged("insert", `SELECT CONCAT_WS('|', name, balance, CHAR_LENGTH(bio), HEX(avatar), shift) FROM dedie_it_customers WHERE code = 'fresh'`,
		"new ☃ row|12.50|9000|CAFE|P3DT0H0M1S")
	converged("large object update", `SELECT CONCAT_WS('|', CHAR_LENGTH(bio), born, small) FROM dedie_it_customers WHERE id = 7`, "15034|2001-02-03 00:00:00|42")
	converged("primary key update", `SELECT COUNT(*) FROM dedie_it_invoices WHERE id > 1000000`, "50")
	converged("unique swap", `SELECT GROUP_CONCAT(code ORDER BY id SEPARATOR ',') FROM dedie_it_customers WHERE id IN (1, 2, 3, 4)`, "c2,c1,moving,c3")
	converged("mixed-case table", "SELECT GROUP_CONCAT(`Note` ORDER BY `Id` SEPARATOR ';') FROM `Dedie_It_Mixed`", `changed;it's, "quoted" and = and`)
	converged("rollback to a savepoint", `SELECT GROUP_CONCAT(CONCAT(code, '=', medium) ORDER BY id SEPARATOR ',') FROM dedie_it_customers WHERE id IN (6, 8, 9)`, "c6=77,c8=8000,c9=9000")
	converged("rollback", `SELECT COUNT(*) FROM dedie_it_customers WHERE code = 'rolled back'`, "0")
	converged("fractional keys", `SELECT GROUP_CONCAT(CONCAT(id + 0E0, '=', a, '/', CHAR_LENGTH(b)) ORDER BY id SEPARATOR ',') FROM dedie_it_wide WHERE id < 100`,
		"1=a of 1/4000,1.5=changed/9,7.125=a of -3/4000")

	// Pause, change the source while nothing is listening, and resume.
	rep.SetDesired("pause")
	if r := <-done; r.err != nil || r.out != migrate.Paused {
		t.Fatalf("pause: %v, %v", r.out, r.err)
	}
	mustExec(t, ctx, src,
		`UPDATE dedie_it_customers SET status = 'P' WHERE id <= 500`,
		`DELETE FROM dedie_it_customers WHERE id BETWEEN 2500 AND 2520`,
		`TRUNCATE TABLE dedie_it_events`,
	)
	_, st := rep.snapshot()
	rep.SetDesired("run")
	start(st)
	converged("changes made while paused", `SELECT COUNT(*) FROM dedie_it_customers WHERE status = 'P'`, "500")
	converged("truncate", `SELECT COUNT(*) FROM dedie_it_events`, "0")

	rep.SetDesired("cutover")
	if r := <-done; r.err != nil || r.out != migrate.Completed {
		t.Fatalf("cutover: %v, %v", r.out, r.err)
	}
	_, st = rep.snapshot()
	t.Logf("applied %d transaction(s), %d row(s), %d anomalies", st.TxApplied, st.RowsApplied, st.Anomalies)
	rep.validated(t)
	if n := logGroups(t, ctx, src); n != 1 {
		t.Errorf("primary key logging is on for %d table(s) afterwards; only the one switched on before the job should remain", n)
	}
	// The cascade ran on the source; the target must not have kept the
	// invoices of deleted customers, nor lost any other.
	compare(t, ctx, src, dst)
	checkSchema(t, ctx, dst)
}

// TestMigrationExistingObjects walks one target database through the
// three things an administrator can choose when it already holds objects
// of the migration's names: refuse, keep them and migrate the rest, or
// replace them.
func TestMigrationExistingObjects(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	srcCfg, dstCfg, _, dst := setup(t, ctx)

	// A table of the migration's name with other columns and a row of its
	// own, and a foreign key elsewhere that holds a name the migration
	// needs: MySQL names foreign keys per database.
	mustExec(t, ctx, dst,
		`CREATE TABLE dedie_it_customers (id INT PRIMARY KEY, note VARCHAR(20))`,
		`INSERT INTO dedie_it_customers VALUES (1, 'mine')`,
		`CREATE TABLE other_parent (id INT PRIMARY KEY)`,
		`CREATE TABLE other_child (id INT PRIMARY KEY, parent INT, CONSTRAINT dedie_it_inv_cust FOREIGN KEY (parent) REFERENCES other_parent (id))`,
	)
	query := func(q string) string {
		t.Helper()
		var got sql.NullString
		if err := dst.QueryRowContext(ctx, q).Scan(&got); err != nil {
			t.Fatalf("%v\n%s", err, q)
		}
		return got.String
	}
	const (
		mine     = `SELECT GROUP_CONCAT(CONCAT_WS('|', id, note)) FROM dedie_it_customers`
		tables   = `SELECT GROUP_CONCAT(table_name ORDER BY table_name) FROM information_schema.tables WHERE table_schema = DATABASE()`
		keyOwner = `SELECT GROUP_CONCAT(table_name) FROM information_schema.table_constraints WHERE constraint_schema = DATABASE() AND constraint_name = 'dedie_it_inv_cust'`
	)
	base := migrate.Config{Mode: migrate.ModeOffline, Tables: []string{"dedie_it_customers", "dedie_it_invoices", "dedie_it_events"}}
	preflightFor := func(policy string) (*migrate.Report, map[string]migrate.Check) {
		t.Helper()
		cfg := base
		cfg.OnExisting = policy
		report, err := Preflight(ctx, srcCfg, dstCfg, cfg)
		if err != nil {
			t.Fatal(err)
		}
		checks := map[string]migrate.Check{}
		for _, c := range report.Checks {
			checks[c.Name] = c
			if c.Name == "Target is empty" || c.Name == "Existing objects" {
				t.Logf("%-7s %-18s %-4s %s", policy, c.Name, c.Status, c.Detail)
			}
		}
		return report, checks
	}
	existingOf := func(r *migrate.Report) string {
		var out []string
		for _, o := range r.Existing {
			out = append(out, o.Kind+" "+o.Name)
		}
		return strings.Join(out, "; ")
	}
	run := func(job, policy string) (migrate.Outcome, error, *memReporter) {
		cfg := base
		cfg.OnExisting = policy
		rep := &memReporter{t: t, desired: "run", tables: map[string]map[string]any{}}
		out, err := Run(ctx, job, cfg, State{}, srcCfg, dstCfg, rep)
		return out, err, rep
	}
	const first = "table dedie_it_customers; foreign key dedie_it_inv_cust on other_child"

	// Without a choice the job refuses and touches nothing.
	report, checks := preflightFor("")
	if report.OK || checks["Target is empty"].Status != "fail" || checks["Existing objects"].Status != "fail" || existingOf(report) != first {
		t.Errorf("fail: ok %v, checks %v / %v, existing %q", report.OK, checks["Target is empty"].Status, checks["Existing objects"].Status, existingOf(report))
	}
	if !strings.Contains(checks["Target is empty"].Detail, "dedie_it_customers") || !strings.Contains(checks["Existing objects"].Detail, "dedie_it_inv_cust on other_child") {
		t.Errorf("fail: the checks do not name what exists")
	}
	if out, err, _ := run("job-fail", migrate.ExistingFail); err == nil || !strings.Contains(err.Error(), "preflight failed") {
		t.Errorf("fail: run ended with %v, %v", out, err)
	}
	if got := query(mine); got != "1|mine" {
		t.Errorf("fail: the existing table now holds %q", got)
	}
	if got := query(tables); got != "dedie_it_customers,other_child,other_parent" {
		t.Errorf("fail: the target now has %s", got)
	}

	// Skipping keeps what exists exactly as it is and migrates the rest.
	report, checks = preflightFor(migrate.ExistingSkip)
	if !report.OK || checks["Target is empty"].Status != "warn" || checks["Existing objects"].Status != "warn" || existingOf(report) != first {
		t.Errorf("skip: ok %v, checks %v / %v, existing %q", report.OK, checks["Target is empty"].Status, checks["Existing objects"].Status, existingOf(report))
	}
	if !strings.Contains(checks["Target is empty"].Detail, "kept exactly as they are") {
		t.Errorf("skip: the check does not say the tables are kept: %s", checks["Target is empty"].Detail)
	}
	out, err, rep := run("job-skip", migrate.ExistingSkip)
	if err != nil || out != migrate.Completed {
		t.Fatalf("skip: %v, %v", out, err)
	}
	_, st := rep.snapshot()
	if len(st.SkippedTables) != 1 || !strings.HasSuffix(st.SkippedTables[0], ".DEDIE_IT_CUSTOMERS") {
		t.Errorf("skip: remembered tables %v", st.SkippedTables)
	}
	if !st.ExistingDecided || strings.Join(st.SkippedObjects, ",") != "foreign key dedie_it_inv_cust" {
		t.Errorf("skip: decided %v, remembered objects %v", st.ExistingDecided, st.SkippedObjects)
	}
	rep.validated(t)
	if _, touched := rep.tables["dedie_it_customers"]; touched || len(rep.tables) != 2 {
		t.Errorf("skip: tables worked on: %v", rep.tables)
	}
	if got := query(mine); got != "1|mine" {
		t.Errorf("skip: the existing table now holds %q", got)
	}
	if got := query(`SELECT GROUP_CONCAT(column_name ORDER BY ordinal_position) FROM information_schema.columns WHERE table_schema = DATABASE() AND table_name = 'dedie_it_customers'`); got != "id,note" {
		t.Errorf("skip: the existing table now has columns %s", got)
	}
	if got := query(`SELECT CONCAT((SELECT COUNT(*) FROM dedie_it_invoices), ',', (SELECT COUNT(*) FROM dedie_it_events))`); got != "3000,1000" {
		t.Errorf("skip: migrated rows %s", got)
	}
	if got := query(keyOwner); got != "other_child" {
		t.Errorf("skip: foreign key dedie_it_inv_cust is on %q", got)
	}
	// The view over the invoices came along: everything it reads is
	// among the tables that were migrated.
	if got := query(tables); got != "dedie_it_customers,dedie_it_events,dedie_it_invoices,dedie_it_totals,other_child,other_parent" {
		t.Errorf("skip: the target now has %s", got)
	}

	// Replacing drops what exists, the tables of the run before included,
	// and puts the source's in its place.
	report, checks = preflightFor(migrate.ExistingReplace)
	// The view is the one the run before created; this job would create
	// it again, so it is in the way like the tables.
	const second = "table dedie_it_customers; table dedie_it_events; table dedie_it_invoices; view dedie_it_totals; foreign key dedie_it_inv_cust on other_child"
	if !report.OK || checks["Target is empty"].Status != "warn" || checks["Existing objects"].Status != "warn" || existingOf(report) != second {
		t.Errorf("replace: ok %v, checks %v / %v, existing %q", report.OK, checks["Target is empty"].Status, checks["Existing objects"].Status, existingOf(report))
	}
	if !strings.Contains(checks["Target is empty"].Detail, "DROPPED") || !strings.Contains(checks["Existing objects"].Detail, "DROPPED") {
		t.Errorf("replace: the checks do not say what is dropped")
	}
	out, err, rep = run("job-replace", migrate.ExistingReplace)
	if err != nil || out != migrate.Completed {
		t.Fatalf("replace: %v, %v", out, err)
	}
	_, st = rep.snapshot()
	if !st.ExistingDecided || len(st.SkippedTables) != 0 || len(st.SkippedObjects) != 0 {
		t.Errorf("replace: decided %v, skipped %v %v", st.ExistingDecided, st.SkippedTables, st.SkippedObjects)
	}
	rep.validated(t)
	if len(rep.tables) != 3 {
		t.Errorf("replace: tables worked on: %v", rep.tables)
	}
	if got := query(`SELECT CONCAT_WS(',', (SELECT COUNT(*) FROM dedie_it_customers), (SELECT COUNT(*) FROM dedie_it_invoices), (SELECT COUNT(*) FROM dedie_it_events),
			(SELECT name FROM dedie_it_customers WHERE code = 'c7'))`); got != "3000,3000,1000,user 7 ☃" {
		t.Errorf("replace: the target holds %s", got)
	}
	if got := query(keyOwner); got != "dedie_it_invoices" {
		t.Errorf("replace: foreign key dedie_it_inv_cust is on %q", got)
	}
	if got := query(tables); got != "dedie_it_customers,dedie_it_events,dedie_it_invoices,dedie_it_totals,other_child,other_parent" {
		t.Errorf("replace: the target now has %s", got)
	}
}

// previewLine writes one statement of a preview for comparison.
func previewLine(s migrate.Statement) string { return s.Phase + " | " + s.Kind + " | " + s.Name }

// findStatement returns the previewed statement of that kind and name.
func findStatement(t *testing.T, list []migrate.Statement, kind, name string) migrate.Statement {
	t.Helper()
	for _, s := range list {
		if s.Kind == kind && s.Name == name {
			return s
		}
	}
	t.Fatalf("the preview has no %s %s", kind, name)
	return migrate.Statement{}
}

// checkPhaseOrder fails unless the statements come phase by phase, in the
// order a job moves through the phases, each complete and unterminated.
func checkPhaseOrder(t *testing.T, list []migrate.Statement) {
	t.Helper()
	order := map[string]int{migrate.PhaseSchema: 1, migrate.PhaseIndexing: 2, migrate.PhaseCutover: 3}
	last := 0
	for _, s := range list {
		n := order[s.Phase]
		if n == 0 || n < last {
			t.Errorf("%s: out of phase order", previewLine(s))
		}
		last = n
		if s.Kind == "" || s.Name == "" || strings.TrimSpace(s.SQL) == "" || strings.HasSuffix(strings.TrimSpace(s.SQL), ";") {
			t.Errorf("%s: incomplete or terminated statement %q", previewLine(s), s.SQL)
		}
	}
}

// TestMigrationPreview reads the statements of a migration before it is
// started. A preview must be the real script, so the test runs it, as it
// is, against the target; and it must be only a preview, so both databases
// are compared with what they were before.
func TestMigrationPreview(t *testing.T) {
	var _ migrate.Previewer = pipeline{}
	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Minute)
	defer cancel()
	srcCfg, dstCfg, src, _ := setup(t, ctx)
	// Read current figures from information_schema, not cached statistics.
	dst, err := mysql.Open(ctx, dstCfg, map[string]string{"information_schema_stats_expiry": "0", "group_concat_max_len": "1000000"})
	if err != nil {
		t.Fatal(err)
	}
	defer dst.Close()

	// Everything a job leaves behind: on the source the key logging it
	// switches on, beside the schema's own objects; on the target whatever
	// the database holds, the checkpoint table included.
	state := func() (source, target string) {
		t.Helper()
		if err := src.QueryRowContext(ctx, `SELECT (SELECT COUNT(*) FROM user_objects) || ' | ' || (SELECT COUNT(*) FROM user_log_groups) FROM dual`).Scan(&source); err != nil {
			t.Fatal(err)
		}
		if err := dst.QueryRowContext(ctx, `SELECT CONCAT_WS(' | ',
			(SELECT COALESCE(GROUP_CONCAT(CONCAT(table_type, ' ', table_name) ORDER BY table_name), '') FROM information_schema.tables WHERE table_schema = DATABASE()),
			(SELECT COALESCE(GROUP_CONCAT(CONCAT(table_name, '.', constraint_name) ORDER BY table_name, constraint_name), '') FROM information_schema.table_constraints WHERE constraint_schema = DATABASE()),
			(SELECT COALESCE(GROUP_CONCAT(DISTINCT CONCAT(table_name, '.', index_name) ORDER BY table_name, index_name), '') FROM information_schema.statistics WHERE table_schema = DATABASE()))`).Scan(&target); err != nil {
			t.Fatal(err)
		}
		return source, target
	}
	srcBefore, dstBefore := state()
	if dstBefore != " |  | " {
		t.Fatalf("the target is not empty: %s", dstBefore)
	}
	unchanged := func(when string) {
		t.Helper()
		source, target := state()
		if source != srcBefore {
			t.Errorf("%s changed the source:\nbefore %s\nafter  %s", when, srcBefore, source)
		}
		if target != dstBefore {
			t.Errorf("%s changed the target:\nbefore %s\nafter  %s", when, dstBefore, target)
		}
	}

	// A job that follows changes, which would switch key logging on at the
	// source; its preview must not.
	cfg := migrate.Config{}
	list, err := pipeline{}.Preview(ctx, srcCfg, dstCfg, cfg)
	if err != nil {
		t.Fatal(err)
	}
	unchanged("the preview")
	// The table of JSON and BOOLEAN columns exists on newer servers only
	// and is left out of the comparison.
	outline := func(list []migrate.Statement) string {
		var lines []string
		for _, s := range list {
			if !strings.Contains(s.Name, "dedie_it_modern") {
				lines = append(lines, previewLine(s))
			}
		}
		return strings.Join(lines, "\n")
	}
	// Tables before the copy; indexes, among them the one behind the
	// unique constraint, and check constraints after it; foreign keys at
	// the very end. The index on an expression has no translation, and the
	// one on a 4000-character column is longer than MySQL can build.
	want := []string{
		"schema | table | dedie_it_customers", "schema | table | dedie_it_events", "schema | table | dedie_it_invoices",
		"schema | table | dedie_it_wide", "schema | table | Dedie_It_Mixed",
		"indexing | index | dedie_it_customers.dedie_it_cust_code", "indexing | index | dedie_it_customers.dedie_it_cust_nums",
		"indexing | index | dedie_it_wide.dedie_it_wide_tag",
		"indexing | check constraint | dedie_it_customers dedie_it_cust_bal",
		"cutover | foreign key | dedie_it_invoices dedie_it_inv_cust",
		"cutover | view | dedie_it_totals",
	}
	if got := outline(list); got != strings.Join(want, "\n") {
		t.Errorf("preview:\n got:\n%s\nwant:\n%s", got, strings.Join(want, "\n"))
	}
	checkPhaseOrder(t, list)
	for _, exact := range []struct{ kind, name, sql string }{
		{"table", "dedie_it_events", "CREATE TABLE `dedie_it_events` (\n  `kind` varchar(20),\n  `payload` varchar(100),\n  `at` datetime\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin"},
		{"index", "dedie_it_customers.dedie_it_cust_code", "CREATE UNIQUE INDEX `dedie_it_cust_code` ON `dedie_it_customers` (`code`)"},
		{"check constraint", "dedie_it_customers dedie_it_cust_bal", "ALTER TABLE `dedie_it_customers` ADD CONSTRAINT `dedie_it_cust_bal` CHECK (balance >= 0)"},
		{"foreign key", "dedie_it_invoices dedie_it_inv_cust",
			"ALTER TABLE `dedie_it_invoices` ADD CONSTRAINT `dedie_it_inv_cust` FOREIGN KEY (`customer_id`) REFERENCES `dedie_it_customers` (`id`) ON DELETE CASCADE"},
	} {
		if s := findStatement(t, list, exact.kind, exact.name); s.SQL != exact.sql {
			t.Errorf("%s %s:\n got %s\nwant %s", exact.kind, exact.name, s.SQL, exact.sql)
		}
	}
	customers := findStatement(t, list, "table", "dedie_it_customers").SQL
	for _, part := range []string{"CREATE TABLE `dedie_it_customers` (", "`id` bigint NOT NULL AUTO_INCREMENT", "`status` char(1) NOT NULL DEFAULT 'A'", "`small` smallint",
		"`huge` decimal(30,0)", "`born` datetime DEFAULT CURRENT_TIMESTAMP", "`seen` datetime(6)", "`tenure` varchar(64)", "`avatar` longblob",
		"`token` varbinary(16) DEFAULT (UNHEX(REPLACE(UUID(), '-', '')))", "PRIMARY KEY (`id`)"} {
		if !strings.Contains(customers, part) {
			t.Errorf("CREATE TABLE of customers lacks %q:\n%s", part, customers)
		}
	}

	// A table-level job previews its tables only; the foreign key to a
	// table that is not migrated is left out. The view comes along,
	// because the one table it reads is the one being migrated.
	scoped, err := Preview(ctx, srcCfg, dstCfg, migrate.Config{Mode: migrate.ModeOffline, Tables: []string{"DEDIE_IT_INVOICES"}})
	if err != nil {
		t.Fatal(err)
	}
	if got := outline(scoped); got != "schema | table | dedie_it_invoices\ncutover | view | dedie_it_totals" {
		t.Errorf("table scope previews:\n%s", got)
	}

	// What the target already has: a table of the migration, and a check
	// constraint of its name on a table it has nothing to do with; MySQL
	// names those per database. From here on the previews depend on it.
	for _, stmt := range []string{
		"CREATE TABLE dedie_it_events (other INT) ENGINE=InnoDB",
		"INSERT INTO dedie_it_events VALUES (42)",
		"CREATE TABLE unrelated (a INT, CONSTRAINT dedie_it_cust_bal CHECK (a > 0)) ENGINE=InnoDB",
	} {
		mustExec(t, ctx, dst, stmt)
	}
	_, dstBefore = state()

	// Under the default policy the job would refuse to start; its preview
	// still shows every object as it would be created.
	again, err := Preview(ctx, srcCfg, dstCfg, cfg)
	if err != nil {
		t.Fatal(err)
	}
	if fmt.Sprint(again) != fmt.Sprint(list) {
		t.Error("the default policy previews something else once the target holds some of the names")
	}

	// Kept: the table and the check constraint are left out. Nothing is
	// dropped.
	cfg.OnExisting = migrate.ExistingSkip
	skip, err := Preview(ctx, srcCfg, dstCfg, cfg)
	if err != nil {
		t.Fatal(err)
	}
	checkPhaseOrder(t, skip)
	if len(skip) != len(list)-2 {
		t.Errorf("skip previews %d statements of %d", len(skip), len(list))
	}
	for _, s := range skip {
		if s.Kind == "drop" || s.Name == "dedie_it_events" || s.Kind == "check constraint" {
			t.Errorf("skip previews %s: %s", previewLine(s), s.SQL)
		}
	}

	// Replaced: the drops come first, then the whole migration.
	cfg.OnExisting = migrate.ExistingReplace
	replace, err := Preview(ctx, srcCfg, dstCfg, cfg)
	if err != nil {
		t.Fatal(err)
	}
	checkPhaseOrder(t, replace)
	drops := []migrate.Statement{
		{Phase: migrate.PhaseSchema, Kind: "drop", Name: "dedie_it_events", SQL: "DROP TABLE `dedie_it_events`"},
		{Phase: migrate.PhaseSchema, Kind: "drop", Name: "dedie_it_cust_bal on unrelated", SQL: "ALTER TABLE `unrelated` DROP CHECK `dedie_it_cust_bal`"},
	}
	if len(replace) != len(drops)+len(list) || fmt.Sprint(replace[:len(drops)]) != fmt.Sprint(drops) || fmt.Sprint(replace[len(drops):]) != fmt.Sprint(list) {
		t.Errorf("replace previews:\n%v", replace)
	}
	unchanged("the previews")

	// The preview is the script: every statement runs, in order, as it is,
	// on a session set up like the job's. Nothing in it depends on the rows
	// the job would copy in between.
	run, err := mysql.Open(ctx, dstCfg, targetParams)
	if err != nil {
		t.Fatal(err)
	}
	defer run.Close()
	for _, s := range replace {
		if _, err := run.ExecContext(ctx, s.SQL); err != nil {
			t.Fatalf("%s: %v\n%s", previewLine(s), err, s.SQL)
		}
	}
	_, built := state()
	for _, part := range []string{"BASE TABLE dedie_it_customers,BASE TABLE dedie_it_events,BASE TABLE dedie_it_invoices", "BASE TABLE Dedie_It_Mixed", "BASE TABLE dedie_it_wide",
		"dedie_it_customers.dedie_it_cust_bal,dedie_it_customers.dedie_it_cust_code,dedie_it_customers.PRIMARY", "dedie_it_invoices.dedie_it_inv_cust",
		"dedie_it_customers.dedie_it_cust_code,dedie_it_customers.dedie_it_cust_nums", "dedie_it_wide.dedie_it_wide_tag"} {
		if !strings.Contains(built, part) {
			t.Errorf("the script did not build %q:\n%s", part, built)
		}
	}
}
