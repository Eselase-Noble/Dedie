// setup prepares the source schema and a scratch database on the target.
func setup(t *testing.T, ctx context.Context) (srcCfg, dstCfg connector.Config, src, dst *sql.DB) {
	srcCfg, dstAdmin := testConfig(t, "DEDIE_TEST_ORACLE_SOURCE"), testConfig(t, "DEDIE_TEST_MYSQL_TARGET")
	src, err := oracle.Open(ctx, srcCfg)
	if err != nil {
		t.Fatal(err)
	}
	db := fmt.Sprintf("dedie_o_%d", time.Now().UnixNano())
	admin, err := mysql.Open(ctx, dstAdmin, nil)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := admin.ExecContext(ctx, "CREATE DATABASE "+db+" CHARACTER SET utf8mb4"); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		bg := context.Background()
		for _, stmt := range drops {
			src.ExecContext(bg, stmt)
		}
		src.Close()
		admin.ExecContext(bg, "DROP DATABASE IF EXISTS "+db)
		admin.Close()
	})
	for _, stmt := range drops {
		src.ExecContext(ctx, stmt)
	}
	list := fixture
	_, version, _ := oracle.Version(ctx, src)
	if oracle.VersionNum(version) >= 230000 {
		list = append(list[:len(list):len(list)],
			`CREATE TABLE dedie_it_modern (id NUMBER(9) PRIMARY KEY, doc JSON, ok BOOLEAN DEFAULT TRUE)`,
			`INSERT INTO dedie_it_modern VALUES (1, JSON('{"a": [1, 2], "b": "x"}'), TRUE)`,
			`INSERT INTO dedie_it_modern VALUES (2, NULL, FALSE)`)
	}
	for _, stmt := range list {
		if _, err := src.ExecContext(ctx, stmt); err != nil {
			t.Fatalf("fixture: %v\n%s", err, stmt)
		}
	}
	dstCfg = dstAdmin
	dstCfg.Database = db
	if dst, err = mysql.Open(ctx, dstCfg, nil); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { dst.Close() })
	return srcCfg, dstCfg, src, dst
}

